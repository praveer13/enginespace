/// The adapters that a stream may load on a pool: the id and the pages, for the Pool game's catalog at the pool's page size.
type Catalog = &'static [(u32, usize)];
const CATALOG_ONE_GROUP: Catalog = &[(0, 4), (1, 8), (2, 32)];
const CATALOG_TWO_KINDS: Catalog = &[(0, 4), (1, 7), (2, 26)];
const CATALOG_STATE: Catalog = &[(0, 2), (1, 4), (2, 16)];
const CATALOG_SAME_SIZE: Catalog = &[(0, 4), (1, 7), (2, 26)];

/// What a seeded stream is made of.
struct Stream {
    name: &'static str,
    spec: &'static str,
    ops: usize,
    /// The adapters it may load. Empty: none, and no call to unload one that is not there.
    catalog: Catalog,
    /// Whether it may reset the pool (and call a reset that must be refused).
    reset: bool,
}

const VOCAB: usize = 50_000;
const NOBODY: u32 = 1_000_000_000;

struct Conversation {
    seq: Vec<u32>,
    adapter: Option<u32>,
    turns: usize,
    running: bool,
}

struct Active {
    req: u32,
    session: usize,
    left: usize,
    tokens: Vec<u32>,
}

/// The operations of a stream, drawn as an engine's workload is: conversations whose each turn extends the last turn's whole sequence,
/// shared system prompts, decode steps, requests that finish or cannot grow and are let go, adapters that come and go, and now and
/// then a call that must be refused. It is adaptive: the next operation depends on what the manager answered, so a manager that
/// answers wrong is judged where it first does.
struct Gen {
    rng: Rng,
    unit: usize,
    cap: usize,
    catalog: Catalog,
    reset: bool,
    system: Vec<Vec<u32>>,
    sessions: Vec<Conversation>,
    active: Vec<Active>,
    resident: Vec<u32>,
    next_req: u32,
    owed: Option<u32>,
    last: Last,
}

enum Last {
    None,
    Admit { session: usize, req: u32, prompt: Vec<u32> },
    Append { req: u32, tokens: Vec<u32> },
    Finish,
    Load(u32),
    Unload(u32),
}

impl Gen {
    fn new(seed: u32, stream: &Stream, spec: &Spec) -> Gen {
        let mut rng = Rng::seeded(seed);
        let unit = spec.groups.iter().map(|g| g.block_tokens).max().unwrap_or(1);
        let system: Vec<Vec<u32>> = (0..3)
            .map(|_| {
                let n = rng.range(unit + 3, 4 * unit + 5);
                (0..n).map(|_| rng.below(VOCAB) as u32).collect()
            })
            .collect();
        let mut gen = Gen {
            rng,
            unit,
            cap: 10 * unit,
            catalog: stream.catalog,
            reset: stream.reset,
            system,
            sessions: Vec::new(),
            active: Vec::new(),
            resident: Vec::new(),
            next_req: 0,
            owed: None,
            last: Last::None,
        };
        for _ in 0..4 {
            gen.sessions.push(Conversation { seq: Vec::new(), adapter: None, turns: 0, running: false });
        }
        for s in 0..gen.sessions.len() {
            gen.begin(s);
        }
        gen
    }

    fn chance(&mut self, permille: usize) -> bool {
        self.rng.below(1000) < permille
    }

    fn tokens(&mut self, count: usize) -> Vec<u32> {
        (0..count).map(|_| self.rng.below(VOCAB) as u32).collect()
    }

    /// A conversation starts over: from a shared system prompt or from nothing, on the base model or on a resident adapter.
    fn begin(&mut self, s: usize) {
        let from_system = self.chance(700);
        let seq = if from_system { self.system[self.rng.below(self.system.len())].clone() } else { Vec::new() };
        let mut options: Vec<Option<u32>> = vec![None];
        options.extend(self.resident.iter().map(|&a| Some(a)));
        let adapter = options[self.rng.below(options.len())];
        let session = &mut self.sessions[s];
        session.seq = seq;
        session.turns = 0;
        session.adapter = adapter;
    }

    /// A request is let go: its conversation takes its whole sequence for the next turn.
    fn let_go(&mut self, index: usize) -> Op {
        let active = self.active.remove(index);
        let turns_to_live = self.rng.range(3, 5);
        let long = {
            let session = &mut self.sessions[active.session];
            session.running = false;
            session.seq = active.tokens;
            session.turns += 1;
            session.turns >= turns_to_live || session.seq.len() > self.cap
        };
        if long {
            self.begin(active.session);
        }
        Op::Finish { req: active.req }
    }

    fn next(&mut self) -> Op {
        if let Some(req) = self.owed.take() {
            if let Some(index) = self.active.iter().position(|a| a.req == req) {
                self.last = Last::Finish;
                return self.let_go(index);
            }
        }
        let idle: Vec<usize> = (0..self.sessions.len()).filter(|&s| !self.sessions[s].running).collect();
        let missing: Vec<(u32, usize)> = self.catalog.iter().copied().filter(|(id, _)| !self.resident.contains(id)).collect();
        let unused: Vec<u32> = self.resident.iter().copied().filter(|a| !self.active.iter().any(|r| self.sessions[r.session].adapter == Some(*a))).collect();
        let max_running = 3;
        let running = self.active.len();
        let weights = [
            if running < max_running && !idle.is_empty() { 26 } else { 0 },
            if running > 0 { 40 } else { 0 },
            if running > 0 { 14 + if running >= max_running { 20 } else { 0 } } else { 0 },
            if !missing.is_empty() { 4 } else { 0 },
            if !unused.is_empty() { 2 } else { 0 },
            if self.reset && running == 0 { 2 } else { 0 },
            3,
        ];
        let total: usize = weights.iter().sum();
        let mut roll = self.rng.below(total);
        let mut act = 0;
        for (i, w) in weights.iter().enumerate() {
            if roll < *w {
                act = i;
                break;
            }
            roll -= w;
        }
        match act {
            0 => {
                let s = idle[self.rng.below(idle.len())];
                if let Some(a) = self.sessions[s].adapter {
                    if !self.resident.contains(&a) {
                        self.sessions[s].adapter = None;
                    }
                }
                let ask = if self.chance(800) { self.rng.range(4 * self.unit, 10 * self.unit) } else { self.rng.range(2, 3 * self.unit) };
                let fresh = self.tokens(ask);
                let prompt = [self.sessions[s].seq.as_slice(), fresh.as_slice()].concat();
                let req = self.next_req;
                self.next_req += 1;
                self.last = Last::Admit { session: s, req, prompt: prompt.clone() };
                Op::Admit { req, adapter: self.sessions[s].adapter, prompt }
            }
            1 => {
                let r = self.rng.below(running);
                let count = if self.chance(300) { self.rng.range(self.unit, 3 * self.unit) } else { self.rng.range(1, 3) };
                let tokens = self.tokens(count);
                let req = self.active[r].req;
                self.last = Last::Append { req, tokens: tokens.clone() };
                Op::Append { req, tokens }
            }
            2 => {
                let r = self.rng.below(running);
                self.last = Last::Finish;
                self.let_go(r)
            }
            3 => {
                let (adapter, pages) = missing[self.rng.below(missing.len())];
                self.last = Last::Load(adapter);
                Op::Load { adapter, pages }
            }
            4 => {
                let adapter = unused[self.rng.below(unused.len())];
                self.last = Last::Unload(adapter);
                Op::Unload { adapter }
            }
            5 => {
                self.last = Last::None;
                Op::Reset
            }
            _ => {
                self.last = Last::None;
                let mut refused = vec![Op::Finish { req: NOBODY }, Op::Append { req: NOBODY, tokens: vec![1, 2] }];
                if !self.catalog.is_empty() || self.reset {
                    refused.push(Op::Unload { adapter: NOBODY });
                }
                if running > 0 {
                    let req = self.active[self.rng.below(running)].req;
                    refused.push(Op::Admit { req, adapter: None, prompt: vec![1, 2, 3] });
                    if self.reset {
                        refused.push(Op::Reset);
                    }
                }
                if !self.catalog.is_empty() {
                    refused.push(Op::Admit { req: NOBODY, adapter: Some(NOBODY), prompt: vec![1, 2, 3] });
                    if let Some(&present) = self.resident.first() {
                        refused.push(Op::Load { adapter: present, pages: 1 });
                    }
                    if let Some(user) = self.active.iter().find_map(|r| self.sessions[r.session].adapter) {
                        refused.push(Op::Unload { adapter: user });
                    }
                }
                let at = self.rng.below(refused.len());
                refused.swap_remove(at)
            }
        }
    }

    /// What the manager answered to the operation just drawn.
    fn saw(&mut self, reply: &Reply) {
        let ok = matches!(reply, Reply::Ok { .. });
        match std::mem::replace(&mut self.last, Last::None) {
            Last::Admit { session, req, prompt } => {
                if ok {
                    self.sessions[session].running = true;
                    let left = self.rng.range(1, 14);
                    self.active.push(Active { req, session, left, tokens: prompt });
                } else if self.chance(300) {
                    self.begin(session);
                }
            }
            Last::Append { req, tokens } => {
                if let Some(index) = self.active.iter().position(|a| a.req == req) {
                    if ok {
                        self.active[index].tokens.extend(tokens);
                        self.active[index].left -= 1;
                        if self.active[index].left == 0 {
                            self.owed = Some(req);
                        }
                    } else {
                        self.owed = Some(req);
                    }
                }
            }
            Last::Load(adapter) => {
                if ok {
                    self.resident.push(adapter);
                }
            }
            Last::Unload(adapter) => {
                if ok {
                    self.resident.retain(|&a| a != adapter);
                }
            }
            Last::Finish | Last::None => {}
        }
    }
}

/// Plays a stream on `seed`: every operation is judged, and the stream goes on while the manager is right.
fn stream(seed: u32, stream: &Stream) -> Result<usize, String> {
    let mut run = Run::start(stream.spec).map_err(|why| format!("{}: {why}", stream.name))?;
    let mut gen = Gen::new(seed, stream, &run.spec);
    let mut ops = 0;
    while ops < stream.ops {
        let op = gen.next();
        let reply = run.apply(&op).map_err(|why| format!("{}, operation {} of {}: {why}", stream.name, ops + 1, stream.ops))?;
        gen.saw(&reply);
        ops += 1;
    }
    Ok(ops)
}

/* ------------------------------ checks ------------------------------ */

/// The operations of a seeded stream in each stage's check, and in the gauntlet [estimated].
const STREAM_OPS: [usize; 5] = [120, 120, 100, 150, 150];

fn verdict(id: &'static str, label: &'static str, run: Result<String, String>) -> Check {
    match run {
        Ok(message) => Check::pass(id, label, message),
        Err(message) => Check::fail(id, label, message),
    }
}

/// A check: its scripts, then a stream on the seed.
fn staged(scripts: &[&Script], streams: &[Stream], seed: u32, what: &str) -> Result<String, String> {
    let mut ops = 0;
    for script in scripts {
        ops += play(script)?;
    }
    for (i, s) in streams.iter().enumerate() {
        ops += stream(seed.wrapping_add((i as u32).wrapping_mul(0x9E37_79B9)), s)?;
    }
    Ok(format!("{ops} operations: {what}"))
}

const EVERY: &str = "every reply, every page and every event judged";

pub fn check_one_group(ctx: &Ctx) -> Check {
    let streams = [Stream { name: "the one_group stream", spec: SPEC_ONE_GROUP, ops: STREAM_OPS[0], catalog: &[], reset: false }];
    verdict(ONE_GROUP, ONE_GROUP_LABEL, staged(&[&SCRIPT_ONE_GROUP], &streams, ctx.seed, EVERY))
}

pub fn check_sliding(ctx: &Ctx) -> Check {
    let streams = [Stream { name: "the sliding stream", spec: SPEC_TWO_KINDS, ops: STREAM_OPS[1], catalog: &[], reset: false }];
    verdict(SLIDING, SLIDING_LABEL, staged(&[&SCRIPT_SLIDING], &streams, ctx.seed, EVERY))
}

pub fn check_state(ctx: &Ctx) -> Check {
    let streams = [Stream { name: "the state stream", spec: SPEC_STATE, ops: STREAM_OPS[2], catalog: &[], reset: false }];
    verdict(STATE, STATE_LABEL, staged(&[&SCRIPT_STATE], &streams, ctx.seed, EVERY))
}

pub fn check_hit_all_groups(ctx: &Ctx) -> Check {
    let streams = [Stream { name: "the hit_all_groups stream", spec: SPEC_TWO_KINDS, ops: STREAM_OPS[3], catalog: &[], reset: false }];
    verdict(HIT_ALL_GROUPS, HIT_ALL_GROUPS_LABEL, staged(&[&SCRIPT_HIT, &SCRIPT_SAME_SIZE], &streams, ctx.seed, "every hit the intersection of the groups, and every reply and event judged"))
}

pub fn check_adapter_pages(ctx: &Ctx) -> Check {
    let streams = [Stream { name: "the adapter_pages stream", spec: SPEC_ONE_GROUP, ops: STREAM_OPS[4], catalog: CATALOG_ONE_GROUP, reset: false }];
    verdict(ADAPTER_PAGES, ADAPTER_PAGES_LABEL, staged(&[&SCRIPT_ADAPTERS], &streams, ctx.seed, EVERY))
}

pub fn check_gauntlet(ctx: &Ctx) -> Check {
    let streams = [
        Stream { name: "stream 1 of 4", spec: SPEC_ONE_GROUP, ops: 440, catalog: CATALOG_ONE_GROUP, reset: true },
        Stream { name: "stream 2 of 4", spec: SPEC_TWO_KINDS, ops: 460, catalog: CATALOG_TWO_KINDS, reset: true },
        Stream { name: "stream 3 of 4", spec: SPEC_STATE, ops: 440, catalog: CATALOG_STATE, reset: true },
        Stream { name: "stream 4 of 4", spec: SPEC_SAME_SIZE, ops: 460, catalog: CATALOG_SAME_SIZE, reset: true },
    ];
    let scripts = [&SCRIPT_ONE_GROUP, &SCRIPT_SLIDING, &SCRIPT_STATE, &SCRIPT_HIT, &SCRIPT_SAME_SIZE, &SCRIPT_ADAPTERS, &SCRIPT_RESET];
    verdict(GAUNTLET, GAUNTLET_LABEL, staged(&scripts, &streams, ctx.seed, "every reply, every page and every event judged, and the invariants after each"))
}

/// The checks, in grading order. Ids, labels and stages are the site's (src/forge/labs.ts), and `verify:labs` fails when they differ.
pub static CHECKS: [CheckDef; 6] = [
    CheckDef { id: ONE_GROUP, label: ONE_GROUP_LABEL, stage: 1, seeded: true, default_seed: 0x4b01, run: check_one_group },
    CheckDef { id: SLIDING, label: SLIDING_LABEL, stage: 2, seeded: true, default_seed: 0x4b02, run: check_sliding },
    CheckDef { id: STATE, label: STATE_LABEL, stage: 3, seeded: true, default_seed: 0x4b03, run: check_state },
    CheckDef { id: HIT_ALL_GROUPS, label: HIT_ALL_GROUPS_LABEL, stage: 4, seeded: true, default_seed: 0x4b04, run: check_hit_all_groups },
    CheckDef { id: ADAPTER_PAGES, label: ADAPTER_PAGES_LABEL, stage: 5, seeded: true, default_seed: 0x4b05, run: check_adapter_pages },
    CheckDef { id: GAUNTLET, label: GAUNTLET_LABEL, stage: 6, seeded: true, default_seed: 0x4b06, run: check_gauntlet },
];

pub static LAB: Lab = Lab { id: LAB_ID, version: 1, checks: &CHECKS };

/// The full suite on default seeds, in grading order.
pub fn self_checks() -> Vec<Check> {
    CHECKS.iter().map(|c| (c.run)(&Ctx { seed: c.default_seed, fresh: false })).collect()
}


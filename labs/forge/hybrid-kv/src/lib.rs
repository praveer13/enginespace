/// The queue after request `req` finishes, as the rules of the free queue make it: group by group, the request's pages go back last
/// block first, and a page that nobody holds any more joins the queue at the back when it has a hash, so that cached pages leave oldest
/// first, and at the front when it has none, so that it is reused before any cached page is dumped.
fn queue_after_finish(spec: &Spec, before: &Snapshot, req: &RequestView) -> Vec<usize> {
    let mut queue = before.queue.clone();
    let mut refs: BTreeMap<usize, u32> = BTreeMap::new();
    for (page, state) in before.pages.iter().enumerate() {
        if let PageState::Used { refs: held, .. } = state {
            refs.insert(page, *held);
        }
    }
    for table in &req.tables {
        let (mut front, mut back) = (Vec::new(), Vec::new());
        for &page in table.iter().rev().flatten() {
            let held = refs.entry(page).or_insert(1);
            *held = held.saturating_sub(1);
            if *held == 0 {
                match before.pages[page] {
                    PageState::Used { hash: Some(_), .. } if spec.prefix_caching => back.push(page),
                    _ => front.push(page),
                }
            }
        }
        queue.splice(0..0, front);
        queue.extend(back);
    }
    queue
}

/// A request the harness has seen admitted: what it needs to know to say what the manager must answer.
struct Live {
    adapter: Option<u32>,
    tokens: Vec<u32>,
}

/// A manager on a pool, driven one operation at a time. After each operation the harness takes the manager's snapshot and its events
/// and asks the questions of the site's judge: is the reply right (a refusal for a request that exists, or an adapter that does not;
/// the free count; the hit), did a refusal change nothing, do the invariants hold, and are the events the blocks of the request's
/// own tokens. The reply to an operation that fits is not predicted here: the site compares it with its own reference.
struct Run {
    spec: Spec,
    manager: KvManager,
    /// The snapshot after the last operation.
    state: Snapshot,
    consumer: Consumer,
    live: BTreeMap<u32, Live>,
    resident: BTreeMap<u32, usize>,
    done: usize,
}

impl Run {
    fn start(spec_line: &str) -> Result<Run, String> {
        let spec = Spec::parse(spec_line)?;
        let manager = KvManager::new(&spec);
        let state = manager.snapshot().normalized();
        let consumer = Consumer::default();
        let problems = invariants(&spec, &state, &consumer);
        if !problems.is_empty() {
            return Err(format!("a new manager already breaks an invariant: {}", problems.join("; ")));
        }
        Ok(Run { spec, manager, state, consumer, live: BTreeMap::new(), resident: BTreeMap::new(), done: 0 })
    }

    /// The refusal that an operation must get, from what the harness has seen: it is the same whatever the pool holds.
    fn refusal(&self, op: &Op) -> Option<Refusal> {
        match op {
            Op::Admit { req, adapter, .. } => {
                if self.live.contains_key(req) {
                    Some(Refusal::Exists)
                } else if adapter.is_some_and(|a| !self.resident.contains_key(&a)) {
                    Some(Refusal::NoAdapter)
                } else {
                    None
                }
            }
            Op::Append { req, .. } | Op::Finish { req } => (!self.live.contains_key(req)).then_some(Refusal::Unknown),
            Op::Load { adapter, .. } => self.resident.contains_key(adapter).then_some(Refusal::Exists),
            Op::Unload { adapter } => {
                if !self.resident.contains_key(adapter) {
                    Some(Refusal::Unknown)
                } else if self.live.values().any(|l| l.adapter == Some(*adapter)) {
                    Some(Refusal::InUse)
                } else {
                    None
                }
            }
            Op::Reset => (!self.live.is_empty()).then_some(Refusal::Busy),
        }
    }

    /// The problems with the stored blocks an operation published: each is a run of the request's own blocks, in order.
    fn stored_problems(&self, op: &Op, events: &[Event]) -> Vec<String> {
        let mut out = Vec::new();
        let request = match op {
            Op::Admit { req, adapter, prompt } => Some((*adapter, prompt.clone(), *req)),
            Op::Append { req, tokens } => self.live.get(req).map(|l| (l.adapter, [l.tokens.as_slice(), tokens.as_slice()].concat(), *req)),
            _ => None,
        };
        for event in events {
            match event {
                Event::Stored { group, hashes, parent, tokens, adapter } => {
                    let Some((owner, all, req)) = &request else {
                        out.push(format!("events: {} published a stored block", op.describe()));
                        continue;
                    };
                    if adapter != owner {
                        out.push(format!("events: a stored block of request {req} names adapter {adapter:?}, and the request runs on {owner:?}"));
                    }
                    let Some(g) = self.spec.groups.get(*group) else {
                        out.push(format!("events: a stored block names group {group}, and the spec has {}", self.spec.groups.len()));
                        continue;
                    };
                    let size = g.block_tokens;
                    let mut chain = Vec::new();
                    let mut last = 0;
                    for j in 0..all.len() / size {
                        last = block_hash(last, &all[j * size..(j + 1) * size], extra_key(*owner));
                        chain.push(last);
                    }
                    let start = match parent {
                        None => Some(0),
                        Some(p) => chain.iter().position(|h| h == p).map(|i| i + 1),
                    };
                    match start {
                        Some(start) if start + hashes.len() <= chain.len() && hashes.as_slice() == &chain[start..start + hashes.len()] && tokens.as_slice() == &all[start * size..(start + hashes.len()) * size] => {}
                        Some(_) => out.push(format!("events: a stored run of group {} is not the blocks of request {req}'s tokens: the hashes chain the parent, the block's tokens and the extra key", g.id)),
                        None => out.push(format!("events: a stored run of group {} names a parent that is not the hash of any block of request {req}", g.id)),
                    }
                }
                Event::Removed { group, hash } => {
                    if !self.state.cache.iter().any(|e| e.group == *group && e.hash == *hash) {
                        out.push(format!("events: BlockRemoved of {group}:{hash}, which was not cached"));
                    }
                }
                Event::Cleared => {
                    if !matches!(op, Op::Reset) {
                        out.push(format!("events: {} published AllBlocksCleared", op.describe()));
                    }
                }
            }
        }
        out
    }

    /// Runs one operation and judges it. The error names the operation and the checks it breaks, each led by its id.
    fn apply(&mut self, op: &Op) -> Result<Reply, String> {
        let want = self.refusal(op);
        let reply = execute(&mut self.manager, op);
        let after = self.manager.snapshot().normalized();
        let events = self.manager.take_events();
        self.done += 1;
        let n = self.done;
        let mut problems: Vec<String> = Vec::new();

        match (want, reply) {
            (Some(reason), Reply::Ok { .. }) => problems.push(format!("reply: {} should be refused ({}), and the manager accepted it", op.describe(), reason.word())),
            (Some(reason), Reply::Refused { reason: got, .. }) if got != reason => problems.push(format!("reply: {} should be refused ({}), and the manager said {}", op.describe(), reason.word(), got.word())),
            (None, Reply::Refused { reason, .. }) if reason != Refusal::NoPages => problems.push(format!("reply: {} was refused ({}), and nothing is wrong with it", op.describe(), reason.word())),
            _ => {}
        }
        if reply.free() != after.queue.len() {
            problems.push(format!("reply: {} says {} pages free, and the queue holds {}", op.describe(), reply.free(), after.queue.len()));
        }
        if let (Op::Admit { prompt, adapter, .. }, Reply::Ok { hit, .. }) = (op, reply) {
            let longest = longest_hit(&self.spec, &self.state, prompt, *adapter);
            if hit != Some(longest) {
                problems.push(format!("hit: {} reported a hit of {} tokens, and the longest prefix every group holds is {longest}", op.describe(), hit.map_or("no".to_string(), |h| h.to_string())));
            }
        }
        if let (Op::Load { adapter, pages }, Reply::Ok { .. }) = (op, reply) {
            let took = after.adapters.iter().find(|a| a.id == *adapter).map_or(0, |a| a.pages.len());
            if took != *pages {
                problems.push(format!("adapters: adapter {adapter} was loaded with {took} pages, and the load asked for {pages}"));
            }
        }
        if let (Op::Load { pages, .. }, Reply::Refused { reason: Refusal::NoPages, .. }) = (op, reply) {
            if *pages <= self.state.queue.len() {
                problems.push(format!("reply: {} was refused for want of pages, and the pool had {} free", op.describe(), self.state.queue.len()));
            }
        }
        if let (Op::Finish { req }, Reply::Ok { .. }) = (op, reply) {
            if let Some(request) = self.state.requests.iter().find(|r| r.id == *req) {
                let want = queue_after_finish(&self.spec, &self.state, request);
                if let Some(at) = (0..want.len().max(after.queue.len())).find(|&i| want.get(i) != after.queue.get(i)) {
                    let show = |q: &Vec<usize>| q.get(at).map_or("nothing".to_string(), |p| format!("page {p}"));
                    problems.push(format!(
                        "queue: {} should send its pages back last block first, group by group, a page with no hash to the front of the queue and a hashed page to the back: the queue differs at position {at}, where {} should be and {} is",
                        op.describe(),
                        show(&want),
                        show(&after.queue)
                    ));
                }
            }
        }
        if let Reply::Refused { .. } = reply {
            if after != self.state || !events.is_empty() {
                problems.push(format!("atomic: {} was refused and still changed the state", op.describe()));
            }
        }
        problems.extend(self.stored_problems(op, &events));
        for event in &events {
            self.consumer.apply(event);
        }
        problems.extend(invariants(&self.spec, &after, &self.consumer));

        if !problems.is_empty() {
            return Err(format!("operation {n}: {}: {}", op.describe(), problems.join("; ")));
        }
        self.state = after;
        if let Reply::Ok { .. } = reply {
            match op {
                Op::Admit { req, adapter, prompt } => {
                    self.live.insert(*req, Live { adapter: *adapter, tokens: prompt.clone() });
                }
                Op::Append { req, tokens } => {
                    if let Some(l) = self.live.get_mut(req) {
                        l.tokens.extend_from_slice(tokens);
                    }
                }
                Op::Finish { req } => {
                    self.live.remove(req);
                }
                Op::Load { adapter, pages } => {
                    self.resident.insert(*adapter, *pages);
                }
                Op::Unload { adapter } => {
                    self.resident.remove(adapter);
                }
                Op::Reset => {}
            }
        }
        Ok(reply)
    }
}


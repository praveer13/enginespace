//! hybrid-kv — forge lab for TR5a: a hybrid KV cache manager with adapter pages.
//!
//! A model that mixes full attention, sliding windows and recurrent state needs several KV caches. vLLM's hybrid manager serves them from
//! one pool of equal pages, and S-LoRA serves LoRA adapters from the same pool. You write that manager: the pool, the free queue, a
//! table for each group, the prefix cache with its N-group hit, the adapters and the events. It extends lab 02's optional
//! `adapter_unified_paging` check to a whole manager.
//!
//! ┌────────────────────────────────────────────────────────────────┐
//! │  YOU EDIT:   src/manager.rs     (the only file with TODO(you)) │
//! │  DO NOT EDIT this file — it is the grading harness.            │
//! └────────────────────────────────────────────────────────────────┘
//!
//! The checks below are the crate's own, and `cargo test` runs them on your machine. They are not what the site grades. The site
//! (src/forge/invoke.ts) plays seeded operations at your module through `ks_invoke`, a line protocol over the same memory ABI, asks it
//! for its state and its events after each one, and judges everything against its own reference manager (packages/sim/kv): the reply,
//! the hit, whether a refusal left everything as it was, the invariants, and the events. The two agree because they play the same
//! scripts and ask the same questions, and credit comes only from the site's side (ARCHITECTURE §8.3, D-025).
//!
//! A `todo!()` left in your code traps the call that reaches it; the site shows "not implemented yet" with the panic's text, and the
//! other checks still run. An infinite loop is stopped after a time limit per check and marked `timeout`.
//!
//! The checks, one for each stage of the lab (TR5a §5). Each plays a script of operations whose replies are known, then a seeded stream
//! of the kinds of operation its stage has, and judges every operation as it goes:
//!
//! ```text
//!   one_group       one full group: paging, all or nothing, the hash chain, blocks shared by reference count, the order of the queue
//!   sliding         a window lets go of a block at the token its next token stops reading it, and an append counts what it gives back
//!   state           a state group keeps a fixed number of pages, however long the request runs
//!   hit_all_groups  the prefix hit is the longest that every group holds, and not the longest of any one
//!   adapter_pages   adapters take pages of the same pool: shared, all or nothing, unloaded only when nobody runs on them
//!   gauntlet        everything above again, then about 2,000 seeded operations [estimated] on four pools, reset included
//! ```
//!
//! What an operation is judged on. Each message begins with the id of the check it breaks:
//!
//! ```text
//!   reply          a refusal that the request, the adapter or the running requests call for (exists, unknown, no-adapter, in-use, busy),
//!                  the free count, which is the length of the queue, and, in a script, the reply the reference gives
//!   hit            the prefix hit of an admit is the longest prefix that every group holds
//!   atomic         a refused operation changes nothing and publishes nothing
//!   queue          a finish sends its pages back in the order of the rotation; the queue holds the pages that may be allocated
//!   conservation   every page is free, cached, used or an adapter's, and every held page is held by a table
//!   refcounts      a page's count is the number of table entries that hold it
//!   tables         a table follows its group's rule, for the full and the state groups
//!   window         the same, for a sliding group: it lets go of a block once the window has left it, and not before
//!   cache          the cache is the hashed pages, one entry each
//!   adapters       an adapter owns the pages it asked for, and its users are the requests that run on it
//!   events         every block is published exactly once, as a run of the request's own blocks
//! ```
//!
//! The wire, for the site's host and for you if you want to poke your module (`ks_invoke`, one command per call, errors start with
//! `err`). The host sends an operation, then asks for the state:
//!
//! ```text
//!   init <pool> <pageBytes> <tokenBytes> <caching 0|1> <slots|-> <group>...    → ok
//!        group := <id>:<kind>:<layers>:<padLayers>:<blockTokens>:<window|->:<statePages|->
//!   admit <req> <adapter|-> <tokens>                                           → ok <free> hit <tokens> | refused <reason> <free>
//!   append <req> <tokens>                                                      → ok <free> | refused <reason> <free>
//!   finish <req>                                                               → ok <free> | refused <reason> <free>
//!   load <adapter> <pages>                                                     → ok <free> | refused <reason> <free>
//!   unload <adapter>                                                           → ok <free> | refused <reason> <free>
//!   reset                                                                      → ok <free> | refused <reason> <free>
//!   pages      f | c:<g>:<hash> | u:<g>:<refs>:<hash|-> | a:<adapter>, joined by ;          one for each page, by id
//!   queue      <page>,<page>,… or -                                                         the pages an allocation may take, front first
//!   requests   <id>:<adapter|->:<tokens>:<table>/<table>/…, joined by ; or -                a table is <page|_>,… with _ for a block let go
//!   adapters   <id>:<users>:<page>,<page>,… or -, joined by ; or -
//!   cache      <g>:<hash>:<page>, joined by ; or -
//!   events     what was published since the last `events`, joined by ; or -:
//!                S:<g>:<parent|->:<adapter|->:<hash>,<hash>,…:<n>:<digest>     BlockStored; the run's n token ids as a count and a digest
//!                R:<g>:<hash>                                                  BlockRemoved
//!                C                                                             AllBlocksCleared
//! ```
//!
//! `<tokens>` is a list of token ids, each a number or `<first>+<count>` for a run of consecutive ids. A reply is at most 4,096 bytes
//! (the host cuts it) [measured: CALL_REPLY_MAX_BYTES in the host's vendored lab protocol at d478f91], so a pool has at most 128 pages
//! [derived: a page takes about 22 bytes in `pages` and in `cache`]. The reasons are `no-pages`, `no-adapter`, `exists`, `unknown`,
//! `in-use` and `busy`.
//! The bridge below has no manager logic of its own: every command calls YOUR manager, the same code the checks call.


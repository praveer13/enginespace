/// Plays a script: every step must get the reply the reference gives it, and every operation must leave the invariants true.
fn play(script: &Script) -> Result<usize, String> {
    let mut run = Run::start(script.spec).map_err(|why| format!("{}: {why}", script.name))?;
    for (i, step) in script.steps.iter().enumerate() {
        let op = parse_op(step.line).map_err(|why| format!("{}, step {}: {why}", script.name, i + 1))?;
        let at = format!("{}, step {} of {}", script.name, i + 1, script.steps.len());
        let reply = run.apply(&op).map_err(|why| format!("{at}: {why}"))?;
        if reply.wire() != step.reply {
            let note = if step.note.is_empty() { String::new() } else { format!(" ({})", step.note) };
            return Err(format!("{at}: `{}` should answer `{}`, and the manager answered `{}`{note}", step.line, step.reply, reply.wire()));
        }
    }
    Ok(script.steps.len())
}


#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Op {
    Admit { req: u32, adapter: Option<u32>, prompt: Vec<u32> },
    Append { req: u32, tokens: Vec<u32> },
    Finish { req: u32 },
    Load { adapter: u32, pages: usize },
    Unload { adapter: u32 },
    Reset,
}

impl Op {
    pub fn describe(&self) -> String {
        match self {
            Op::Admit { req, adapter: None, prompt } => format!("admit {req} ({} tokens)", prompt.len()),
            Op::Admit { req, adapter: Some(a), prompt } => format!("admit {req} ({} tokens, adapter {a})", prompt.len()),
            Op::Append { req, tokens } => format!("append {req} ({} tokens)", tokens.len()),
            Op::Finish { req } => format!("finish {req}"),
            Op::Load { adapter, pages } => format!("load adapter {adapter} ({pages} pages)"),
            Op::Unload { adapter } => format!("unload adapter {adapter}"),
            Op::Reset => "reset".into(),
        }
    }
}

/// The most pages a pool may have: the state queries must fit in a reply of 4,096 bytes.
pub const MAX_POOL: usize = 128;
/// The most bytes of a reply; the host cuts anything longer, so the bridge refuses to write it.
const MAX_REPLY: usize = 4000;

fn number(text: &str, what: &str) -> Result<usize, String> {
    if text.is_empty() || !text.bytes().all(|b| b.is_ascii_digit()) {
        return Err(format!("{what} is not a number: '{}'", kslab::clip(text, 20)));
    }
    text.parse::<usize>().map_err(|_| format!("{what} is out of range: '{}'", kslab::clip(text, 20)))
}

fn id32(text: &str, what: &str) -> Result<u32, String> {
    u32::try_from(number(text, what)?).map_err(|_| format!("{what} is out of range: '{}'", kslab::clip(text, 20)))
}

fn maybe<T>(text: &str, read: impl Fn(&str) -> Result<T, String>) -> Result<Option<T>, String> {
    if text == "-" {
        Ok(None)
    } else {
        read(text).map(Some)
    }
}

/// `1,5,20+4` is the ids 1, 5, 20, 21, 22 and 23.
fn tokens(text: &str) -> Result<Vec<u32>, String> {
    let mut out = Vec::new();
    for part in text.split(',') {
        match part.split_once('+') {
            None => out.push(id32(part, "a token")?),
            Some((first, run)) => {
                let first = id32(first, "a token")?;
                let run = number(run, "a run length")?;
                if run == 0 || run > 1 << 20 || u64::from(first) + run as u64 > 1 << 32 {
                    return Err(format!("'{}' is not a run of tokens", kslab::clip(part, 20)));
                }
                out.extend((0..run as u32).map(|k| first + k));
            }
        }
    }
    Ok(out)
}

impl Spec {
    /// The spec an `init` line says (`init <pool> <pageBytes> <tokenBytes> <caching 0|1> <slots|-> <group>…`).
    pub fn parse(line: &str) -> Result<Spec, String> {
        let w: Vec<&str> = line.split_whitespace().collect();
        if w.len() < 7 || w[0] != "init" {
            return Err("init takes a pool, a page size, a token size, caching, slots and at least one group".into());
        }
        let pool_pages = number(w[1], "the pool")?;
        if pool_pages == 0 || pool_pages > MAX_POOL {
            return Err(format!("the pool holds 1 to {MAX_POOL} pages, got {pool_pages}"));
        }
        let page_bytes = number(w[2], "the page size")?;
        let token_bytes = number(w[3], "the token size")?;
        let prefix_caching = match w[4] {
            "0" => false,
            "1" => true,
            other => return Err(format!("caching is 0 or 1, got '{}'", kslab::clip(other, 20))),
        };
        if w[5] != "-" {
            return Err("this lab's pool has no adapter slots: adapters take pages of the pool".into());
        }
        let mut groups = Vec::new();
        for token in &w[6..] {
            let f: Vec<&str> = token.split(':').collect();
            if f.len() != 7 {
                return Err(format!("a group is <id>:<kind>:<layers>:<pad>:<block>:<window|->:<statePages|->, got '{}'", kslab::clip(token, 40)));
            }
            let kind = match f[1] {
                "full" => Kind::Full,
                "sliding" => Kind::Sliding,
                "state" => Kind::State,
                other => return Err(format!("the kind of a group is full, sliding or state, got '{}'", kslab::clip(other, 20))),
            };
            let group = Group {
                id: f[0].to_string(),
                kind,
                layers: number(f[2], "the layers of a group")?,
                pad_layers: number(f[3], "the padding of a group")?,
                block_tokens: number(f[4], "the block size of a group")?,
                window: maybe(f[5], |t| number(t, "the window of a group"))?.unwrap_or(0),
                state_pages: maybe(f[6], |t| number(t, "the state pages of a group"))?.unwrap_or(0),
            };
            if group.block_tokens == 0 || group.layers == 0 {
                return Err(format!("group {} has no layers or no tokens in a block", group.id));
            }
            if (group.layers + group.pad_layers) * group.block_tokens * token_bytes != page_bytes {
                return Err(format!("group {}: a block is not exactly one page of {page_bytes} bytes", group.id));
            }
            if kind == Kind::Sliding && group.window < 2 {
                return Err(format!("group {}: a sliding group needs a window of at least 2 tokens", group.id));
            }
            if kind == Kind::State && group.state_pages < 1 {
                return Err(format!("group {}: a state group keeps at least 1 page", group.id));
            }
            groups.push(group);
        }
        Ok(Spec { pool_pages, page_bytes, token_bytes, prefix_caching, groups })
    }
}

/// The operation a command line names.
pub fn parse_op(line: &str) -> Result<Op, String> {
    let w: Vec<&str> = line.split_whitespace().collect();
    let arity = |n: usize, usage: &str| if w.len() == n { Ok(()) } else { Err(format!("{usage} takes {} arguments", n - 1)) };
    match w.first().copied() {
        Some("admit") => {
            arity(4, "admit <req> <adapter|-> <tokens>")?;
            let prompt = tokens(w[3])?;
            Ok(Op::Admit { req: id32(w[1], "a request id")?, adapter: maybe(w[2], |t| id32(t, "an adapter id"))?, prompt })
        }
        Some("append") => {
            arity(3, "append <req> <tokens>")?;
            Ok(Op::Append { req: id32(w[1], "a request id")?, tokens: tokens(w[2])? })
        }
        Some("finish") => {
            arity(2, "finish <req>")?;
            Ok(Op::Finish { req: id32(w[1], "a request id")? })
        }
        Some("load") => {
            arity(3, "load <adapter> <pages>")?;
            let pages = number(w[2], "a page count")?;
            if pages == 0 || pages > MAX_POOL {
                return Err(format!("an adapter takes 1 to {MAX_POOL} pages, got {pages}"));
            }
            Ok(Op::Load { adapter: id32(w[1], "an adapter id")?, pages })
        }
        Some("unload") => {
            arity(2, "unload <adapter>")?;
            Ok(Op::Unload { adapter: id32(w[1], "an adapter id")? })
        }
        Some("reset") => {
            arity(1, "reset")?;
            Ok(Op::Reset)
        }
        _ => Err(format!("unknown command '{}'", kslab::clip(line, 40))),
    }
}

/// Runs an operation on your manager.
pub fn execute(manager: &mut KvManager, op: &Op) -> Reply {
    match op {
        Op::Admit { req, adapter, prompt } => manager.admit(*req, prompt, *adapter),
        Op::Append { req, tokens } => manager.append(*req, tokens),
        Op::Finish { req } => manager.finish(*req),
        Op::Load { adapter, pages } => manager.load_adapter(*adapter, *pages),
        Op::Unload { adapter } => manager.unload_adapter(*adapter),
        Op::Reset => manager.reset(),
    }
}

/// FNV-1a over the four little-endian bytes of each token: how an event names the tokens of a stored run on the wire.
fn token_digest(tokens: &[u32]) -> u32 {
    let mut h = 0x811c_9dc5u32;
    for &t in tokens {
        for k in 0..4 {
            h ^= (t >> (8 * k)) & 0xff;
            h = h.wrapping_mul(0x0100_0193);
        }
    }
    h
}

fn join<T>(items: impl Iterator<Item = T>, text: impl Fn(T) -> String, sep: &str) -> String {
    let parts: Vec<String> = items.map(text).collect();
    if parts.is_empty() {
        "-".into()
    } else {
        parts.join(sep)
    }
}

fn opt<T: ToString>(value: Option<T>) -> String {
    value.map_or("-".into(), |v| v.to_string())
}

pub fn pages_text(s: &Snapshot) -> String {
    s.pages
        .iter()
        .map(|p| match *p {
            PageState::Free => "f".to_string(),
            PageState::Cached { group, hash } => format!("c:{group}:{hash}"),
            PageState::Used { group, refs, hash } => format!("u:{group}:{refs}:{}", opt(hash)),
            PageState::Adapter { adapter } => format!("a:{adapter}"),
        })
        .collect::<Vec<_>>()
        .join(";")
}

pub fn queue_text(s: &Snapshot) -> String {
    join(s.queue.iter(), |p| p.to_string(), ",")
}

pub fn requests_text(s: &Snapshot) -> String {
    let entry = |e: &Option<usize>| e.map_or("_".to_string(), |page| page.to_string());
    let table = |t: &Vec<Option<usize>>| join(t.iter(), entry, ",");
    join(s.requests.iter(), |r| format!("{}:{}:{}:{}", r.id, opt(r.adapter), r.length, r.tables.iter().map(table).collect::<Vec<_>>().join("/")), ";")
}

pub fn adapters_text(s: &Snapshot) -> String {
    join(s.adapters.iter(), |a| format!("{}:{}:{}", a.id, a.users, join(a.pages.iter(), |p| p.to_string(), ",")), ";")
}

pub fn cache_text(s: &Snapshot) -> String {
    join(s.cache.iter(), |e| format!("{}:{}:{}", e.group, e.hash, e.page), ";")
}

pub fn events_text(events: &[Event]) -> String {
    join(
        events.iter(),
        |e| match e {
            Event::Stored { group, hashes, parent, tokens, adapter } => format!(
                "S:{group}:{}:{}:{}:{}:{:08x}",
                opt(*parent),
                opt(*adapter),
                join(hashes.iter(), |h| h.to_string(), ","),
                tokens.len(),
                token_digest(tokens)
            ),
            Event::Removed { group, hash } => format!("R:{group}:{hash}"),
            Event::Cleared => "C".to_string(),
        },
        ";",
    )
}

/// A manager started by `init`, and the snapshot of it after the last operation (taken when a query first asks).
pub struct Session {
    manager: KvManager,
    snapshot: Option<Snapshot>,
}

impl Session {
    fn command(&mut self, verb: &str, command: &str) -> String {
        match verb {
            "pages" | "queue" | "requests" | "adapters" | "cache" => {
                if self.snapshot.is_none() {
                    self.snapshot = Some(self.manager.snapshot().normalized());
                }
                let Some(snapshot) = self.snapshot.as_ref() else { return "err no snapshot".into() };
                match verb {
                    "pages" => pages_text(snapshot),
                    "queue" => queue_text(snapshot),
                    "requests" => requests_text(snapshot),
                    "adapters" => adapters_text(snapshot),
                    _ => cache_text(snapshot),
                }
            }
            "events" => events_text(&self.manager.take_events()),
            _ => match parse_op(command) {
                Ok(op) => {
                    self.snapshot = None;
                    execute(&mut self.manager, &op).wire()
                }
                Err(why) => format!("err {why}"),
            },
        }
    }
}

/// One command of the wire, on a session that may not exist yet. `cargo test` calls it too.
pub fn bridge(session: &mut Option<Session>, command: &str) -> String {
    let command = command.trim();
    let verb = command.split_whitespace().next().unwrap_or("");
    let reply = match verb {
        "" => "err empty command".to_string(),
        "init" => match Spec::parse(command) {
            Ok(spec) => {
                let manager = KvManager::new(&spec);
                *session = Some(Session { manager, snapshot: None });
                "ok".to_string()
            }
            Err(why) => format!("err {why}"),
        },
        _ => match session.as_mut() {
            None => "err not initialized".to_string(),
            Some(s) => s.command(verb, command),
        },
    };
    if reply.len() > MAX_REPLY {
        return format!("err the reply is {} bytes, and the host reads {MAX_REPLY}", reply.len());
    }
    reply
}

thread_local! {
    static SESSION: RefCell<Option<Session>> = const { RefCell::new(None) };
}

/// The site drives your module through this: it writes one command into module memory with `ks_alloc`, calls `ks_invoke`, and reads
/// the reply. The commands call YOUR manager, the same code the checks call, and the bridge has no manager logic of its own.
#[no_mangle]
pub extern "C" fn ks_invoke(in_ptr: u32, in_len: u32) -> u64 {
    kslab::install_panic_hook();
    let bytes = unsafe { kslab::input(in_ptr, in_len) };
    let command = String::from_utf8_lossy(bytes).into_owned();
    let reply = SESSION.with(|session| bridge(&mut session.borrow_mut(), &command));
    kslab::emit_str(&reply)
}


const TWO_32_MIX: u32 = 0x9e37_79b9;

fn mix(h: u32, x: u32) -> u32 {
    let mut v = h.wrapping_add(x).wrapping_add(TWO_32_MIX);
    v ^= v >> 16;
    v = v.wrapping_mul(0x21f0_aaad);
    v ^= v >> 15;
    v = v.wrapping_mul(0x735a_2d97);
    v ^= v >> 15;
    v
}

/// The hash of the block that holds `tokens`, after the block with hash `parent` (0 for none), under the extra key `extra`
/// ([`extra_key`]). A block's hash chains its parent's, so two blocks are the same block only when every token before them and in
/// them is the same. The result is below 2^53. The site checks it against its own, so it is given here and not left to you.
pub fn block_hash(parent: u64, tokens: &[u32], extra: u32) -> u64 {
    let lo = parent as u32;
    let hi = (parent >> 32) as u32;
    let mut a = mix(mix(0x6a09_e667 ^ lo, 1), hi);
    let mut b = mix(mix(0xbb67_ae85 ^ hi, 2), lo);
    let length = tokens.len() as u32;
    a = mix(a, length);
    b = mix(b, length);
    for &t in tokens {
        a = mix(a, t);
        b = mix(b, t ^ 0x5bd1_e995);
    }
    a = mix(a, extra);
    b = mix(b, extra ^ 0x1b87_3593);
    (u64::from(b >> 11) << 32) | u64::from(a)
}

/// The extra key of a request's blocks: 0 for the base model, the adapter's id plus 1 for an adapter, so the same tokens under two
/// adapters are different blocks.
pub fn extra_key(adapter: Option<u32>) -> u32 {
    adapter.map_or(0, |a| a.wrapping_add(1))
}


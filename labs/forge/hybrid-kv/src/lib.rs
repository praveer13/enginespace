/// Which blocks of a request a group keeps, as the lab states the rule: a table of `blocks` entries, the first `skip` of them let go.
fn rule_of(group: &Group, tokens: usize) -> (usize, usize) {
    let blocks = tokens.div_ceil(group.block_tokens);
    let skip = match group.kind {
        Kind::Full => 0,
        // The next token attends to itself and the `window - 1` before it: the tokens before `tokens - window + 1` are skipped.
        Kind::Sliding => (tokens + 1).saturating_sub(group.window) / group.block_tokens,
        // The newest `state_pages` blocks stay, however long the request runs.
        Kind::State => blocks.saturating_sub(group.state_pages),
    };
    (blocks, skip)
}

/// What a consumer of the events believes is cached: for each block, how many more times it was stored than removed.
#[derive(Default)]
struct Consumer(BTreeMap<(usize, u64), i64>);

impl Consumer {
    fn apply(&mut self, event: &Event) {
        let mut add = |group: usize, hash: u64, step: i64| {
            let now = self.0.get(&(group, hash)).copied().unwrap_or(0) + step;
            if now == 0 {
                self.0.remove(&(group, hash));
            } else {
                self.0.insert((group, hash), now);
            }
        };
        match event {
            Event::Stored { group, hashes, .. } => hashes.iter().for_each(|&h| add(*group, h, 1)),
            Event::Removed { group, hash } => add(*group, *hash, -1),
            Event::Cleared => self.0.clear(),
        }
    }
}

/// The problems of a snapshot, each led by the id of the check it breaks: the lab's invariants (GAMES.md §8). Pages are conserved,
/// reference counts match the tables, a table follows its group's rule, the cache is the hashed pages, the queue is the pages that may
/// be allocated, an adapter owns its pages and its users run, and every block is published exactly once.
fn invariants(spec: &Spec, s: &Snapshot, consumer: &Consumer) -> Vec<String> {
    const LISTED: usize = 8;
    let mut out: Vec<String> = Vec::new();
    let mut bad = |id: &str, text: String| {
        if out.len() < LISTED {
            out.push(format!("{id}: {text}"));
        }
    };
    let n = spec.pool_pages;
    if s.pages.len() != n {
        bad("conservation", format!("the state lists {} pages, and the pool has {n}", s.pages.len()));
        return out;
    }
    let groups = &spec.groups;

    // The tables: what each request holds.
    let mut held = vec![0u32; n];
    let mut users: BTreeMap<u32, usize> = BTreeMap::new();
    for r in &s.requests {
        if let Some(a) = r.adapter {
            *users.entry(a).or_default() += 1;
        }
        if r.tables.len() != groups.len() {
            bad("tables", format!("request {} has {} tables, and the spec has {} groups", r.id, r.tables.len(), groups.len()));
            continue;
        }
        if r.length < 1 {
            bad("tables", format!("request {} holds {} tokens", r.id, r.length));
            continue;
        }
        for (g, group) in groups.iter().enumerate() {
            let table = &r.tables[g];
            let (blocks, skip) = rule_of(group, r.length);
            let id = if group.kind == Kind::Sliding { "window" } else { "tables" };
            let at = format!("request {}, group {}", r.id, group.id);
            if table.len() != blocks {
                bad(id, format!("{at}: the table has {} entries, and {} tokens need {blocks}", table.len(), r.length));
            }
            let keeps = format!("the group keeps blocks {skip} to {}", blocks.saturating_sub(1));
            for (j, entry) in table.iter().enumerate() {
                let Some(page) = *entry else {
                    if j >= skip && j < blocks {
                        bad(id, format!("{at}: block {j} is let go, and {keeps}"));
                    }
                    continue;
                };
                if j < skip {
                    bad(id, format!("{at}: block {j} is held though the group has let it go ({keeps})"));
                }
                if page >= n {
                    bad("tables", format!("{at}: block {j} names page {page}, which is not in the pool"));
                    continue;
                }
                held[page] += 1;
                match s.pages[page] {
                    PageState::Used { group: owner, .. } if owner == g => {}
                    PageState::Used { group: owner, .. } => bad("tables", format!("{at}: block {j} is page {page}, which belongs to group {owner}")),
                    other => bad("tables", format!("{at}: block {j} is page {page}, which is {other:?} and not held")),
                }
            }
        }
    }

    // The pages and the queue.
    let mut in_queue = vec![false; n];
    let mut queue_problems = 0;
    for (at, &page) in s.queue.iter().enumerate() {
        if page >= n {
            bad("queue", format!("queue entry {at} is page {page}, which is not in the pool"));
            queue_problems += 1;
        } else if in_queue[page] {
            bad("queue", format!("page {page} is in the queue twice"));
            queue_problems += 1;
        } else {
            in_queue[page] = true;
        }
    }
    let (mut free, mut cached, mut used, mut lent) = (0, 0, 0, 0);
    for page in 0..n {
        match s.pages[page] {
            PageState::Free => {
                free += 1;
                if !in_queue[page] {
                    bad("conservation", format!("page {page} is free and is not in the queue"));
                }
            }
            PageState::Cached { .. } => {
                cached += 1;
                if !in_queue[page] {
                    bad("conservation", format!("page {page} is cached and is not in the queue"));
                }
            }
            PageState::Used { refs, .. } => {
                used += 1;
                if in_queue[page] {
                    bad("queue", format!("page {page} is held and is in the queue"));
                }
                if refs < 1 {
                    bad("refcounts", format!("page {page} is used and has a reference count of {refs}"));
                } else if held[page] == 0 {
                    bad("conservation", format!("page {page} has {refs} references, and no table holds it"));
                } else if held[page] != refs {
                    bad("refcounts", format!("page {page} has {refs} references, and {} table entries hold it", held[page]));
                }
            }
            PageState::Adapter { adapter } => {
                lent += 1;
                if in_queue[page] {
                    bad("queue", format!("page {page} holds an adapter and is in the queue"));
                }
                if held[page] > 0 {
                    bad("adapters", format!("page {page} holds adapter {adapter}, and {} table entries hold it", held[page]));
                }
            }
        }
    }
    if free + cached + used + lent != n {
        bad("conservation", format!("{free} free, {cached} cached, {used} used and {lent} adapter pages are not the {n} of the pool"));
    }
    if queue_problems == 0 && s.queue.len() != free + cached {
        bad("queue", format!("the queue holds {} pages, and {} are free or cached", s.queue.len(), free + cached));
    }

    // The cache: the pages that hold hashes, once each.
    let mut hashed = vec![0usize; n];
    let mut previous = None;
    for e in &s.cache {
        if e.group >= groups.len() {
            bad("cache", format!("cache entry {}:{} names a group the spec does not have", e.group, e.hash));
            continue;
        }
        if previous == Some((e.group, e.hash)) {
            bad("cache", format!("the cache holds {}:{} twice", e.group, e.hash));
        }
        previous = Some((e.group, e.hash));
        if e.page >= n {
            bad("cache", format!("cache entry {}:{} names page {}, which is not in the pool", e.group, e.hash, e.page));
            continue;
        }
        let fine = match s.pages[e.page] {
            PageState::Cached { group, hash } | PageState::Used { group, hash: Some(hash), .. } => group == e.group && hash == e.hash,
            _ => false,
        };
        if !fine {
            bad("cache", format!("cache entry {}:{} is page {}, which is {:?}", e.group, e.hash, e.page, s.pages[e.page]));
        }
        hashed[e.page] += 1;
    }
    for (page, state) in s.pages.iter().enumerate() {
        if matches!(state, PageState::Cached { .. } | PageState::Used { hash: Some(_), .. }) && hashed[page] != 1 {
            bad("cache", format!("page {page} has a hash and {} cache entries", hashed[page]));
        }
    }
    if !spec.prefix_caching && (!s.cache.is_empty() || !consumer.0.is_empty()) {
        bad("cache", "caching is off, and the pool still caches or publishes blocks".into());
    }

    // The adapters: their pages are their own, and their users are the requests that run.
    let mut owned = vec![0usize; n];
    for a in &s.adapters {
        if a.pages.is_empty() {
            bad("adapters", format!("adapter {} is resident and holds no page", a.id));
        }
        for &page in &a.pages {
            if page >= n {
                bad("adapters", format!("adapter {} names page {page}, which is not in the pool", a.id));
                continue;
            }
            owned[page] += 1;
            if s.pages[page] != (PageState::Adapter { adapter: a.id }) {
                bad("adapters", format!("adapter {} lists page {page}, which is {:?}", a.id, s.pages[page]));
            }
        }
        let running = users.get(&a.id).copied().unwrap_or(0);
        if a.users != running {
            bad("adapters", format!("adapter {} has {} users, and {running} running requests use it", a.id, a.users));
        }
    }
    for (page, state) in s.pages.iter().enumerate() {
        if let PageState::Adapter { adapter } = state {
            if owned[page] != 1 {
                bad("adapters", format!("page {page} holds adapter {adapter} and {} adapters list it", owned[page]));
            }
        }
    }
    for (&id, &count) in &users {
        if !s.adapters.iter().any(|a| a.id == id) {
            bad("adapters", format!("{count} running requests use adapter {id}, which is not resident"));
        }
    }

    // The events: what the consumer believes is the cache, and each block was published once.
    let count = |group: usize, hash: u64, c: i64| -> String {
        if c > 1 {
            format!("block {group}:{hash} was published {c} times without a removal")
        } else {
            format!("block {group}:{hash} was removed {} more times than it was stored", -c)
        }
    };
    for e in &s.cache {
        match consumer.0.get(&(e.group, e.hash)) {
            None => bad("events", format!("block {}:{} is cached and was never published", e.group, e.hash)),
            Some(&1) => {}
            Some(&c) => bad("events", count(e.group, e.hash, c)),
        }
    }
    for (&(group, hash), &c) in &consumer.0 {
        if !s.cache.iter().any(|e| e.group == group && e.hash == hash) {
            bad("events", if c == 1 { format!("block {group}:{hash} was published and is not in the cache") } else { count(group, hash, c) });
        }
    }
    out
}

/// The longest prefix of `prompt` that every group holds in the cache of `s`, in tokens: what an admit should report as its hit.
/// It is the definition of the rule, found the plain way: from the longest length a hit may have (a multiple of the least common
/// multiple of the groups' block sizes, and short of the last token), ask every group whether it holds that prefix, and step down.
/// A full group needs every block, a sliding group the blocks its window reads before the edge, a state group the block that holds
/// the state at the edge.
fn longest_hit(spec: &Spec, s: &Snapshot, prompt: &[u32], adapter: Option<u32>) -> usize {
    let cap = prompt.len().saturating_sub(1);
    if !spec.prefix_caching || cap == 0 {
        return 0;
    }
    let align = spec.groups.iter().fold(1, |lcm, g| {
        let (mut a, mut b) = (lcm, g.block_tokens);
        while b != 0 {
            (a, b) = (b, a % b);
        }
        lcm / a * g.block_tokens
    });
    let extra = extra_key(adapter);
    let chains: Vec<Vec<u64>> = spec
        .groups
        .iter()
        .map(|g| {
            let mut parent = 0;
            (0..cap / g.block_tokens)
                .map(|j| {
                    parent = block_hash(parent, &prompt[j * g.block_tokens..(j + 1) * g.block_tokens], extra);
                    parent
                })
                .collect()
        })
        .collect();
    let holds = |g: usize, hash: u64| s.cache.iter().any(|e| e.group == g && e.hash == hash);
    let mut hit = cap - cap % align;
    while hit > 0 {
        let every = spec.groups.iter().enumerate().all(|(g, group)| {
            let m = hit / group.block_tokens;
            let from = match group.kind {
                Kind::Full => 0,
                Kind::Sliding => m.saturating_sub((group.window - 1).div_ceil(group.block_tokens)),
                Kind::State => m - 1,
            };
            (from..m).all(|j| holds(g, chains[g][j]))
        });
        if every {
            return hit;
        }
        hit -= align;
    }
    0
}


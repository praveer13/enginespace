/// What a group keeps of a request's tokens.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    /// Every block, until the request ends.
    Full,
    /// The blocks that cover the last `window` tokens, and no older ones.
    Sliding,
    /// The newest `state_pages` blocks, however long the request runs.
    State,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Group {
    /// `full0`, `sw1`, `state0`: the name the site's messages use.
    pub id: String,
    pub kind: Kind,
    pub layers: usize,
    /// Padding layers that bring the group's block to the pool's page size. A count for the record: the page is already that size.
    pub pad_layers: usize,
    /// Tokens in one block of this group.
    pub block_tokens: usize,
    /// `Sliding` only: the window in tokens. The token being computed attends to itself and the `window - 1` before it.
    pub window: usize,
    /// `State` only: blocks kept for each request.
    pub state_pages: usize,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Spec {
    /// Physical pages in the pool, ids `0 .. pool_pages`. Every group and every adapter draws from them.
    pub pool_pages: usize,
    pub page_bytes: usize,
    pub token_bytes: usize,
    /// Whether full blocks are hashed, cached and found again. Off, a freed page is only free, and nothing is published.
    pub prefix_caching: bool,
    pub groups: Vec<Group>,
}

/// Why an operation was refused. A refusal leaves the state exactly as it was.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Refusal {
    /// The pool cannot supply the pages the operation needs.
    NoPages,
    /// An admit names an adapter that is not resident.
    NoAdapter,
    /// An admit names a request, or a load an adapter, that is already there.
    Exists,
    /// An append or a finish names a request, or an unload an adapter, that is not there.
    Unknown,
    /// An unload of an adapter that a running request uses.
    InUse,
    /// A reset while a request is running.
    Busy,
}

impl Refusal {
    pub fn word(self) -> &'static str {
        match self {
            Refusal::NoPages => "no-pages",
            Refusal::NoAdapter => "no-adapter",
            Refusal::Exists => "exists",
            Refusal::Unknown => "unknown",
            Refusal::InUse => "in-use",
            Refusal::Busy => "busy",
        }
    }
}

/// What an operation answers. `free` is the pages the pool can supply now (the free and the cached), and `hit` the tokens an admit found
/// in the cache.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reply {
    Ok { free: usize, hit: Option<usize> },
    Refused { reason: Refusal, free: usize },
}

impl Reply {
    /// An operation that succeeded.
    pub fn ok(free: usize) -> Reply {
        Reply::Ok { free, hit: None }
    }
    /// An admit that succeeded, with the tokens it found in the cache.
    pub fn admitted(free: usize, hit: usize) -> Reply {
        Reply::Ok { free, hit: Some(hit) }
    }
    pub fn refused(reason: Refusal, free: usize) -> Reply {
        Reply::Refused { reason, free }
    }
    pub fn free(&self) -> usize {
        match *self {
            Reply::Ok { free, .. } | Reply::Refused { free, .. } => free,
        }
    }
    /// The reply as the wire writes it: `ok 12`, `ok 12 hit 32` or `refused no-pages 3`.
    pub fn wire(&self) -> String {
        match *self {
            Reply::Ok { free, hit: None } => format!("ok {free}"),
            Reply::Ok { free, hit: Some(hit) } => format!("ok {free} hit {hit}"),
            Reply::Refused { reason, free } => format!("refused {} {free}", reason.word()),
        }
    }
}

/// One physical page, in one of four states.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PageState {
    /// Nothing in it.
    Free,
    /// A hashed block that nobody holds: a hit can bring it back, and an allocation can evict it.
    Cached { group: usize, hash: u64 },
    /// Held by `refs` requests' tables.
    Used { group: usize, refs: u32, hash: Option<u64> },
    /// Part of an adapter.
    Adapter { adapter: u32 },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RequestView {
    pub id: u32,
    pub adapter: Option<u32>,
    /// Tokens the request holds KV for: its prompt and everything appended.
    pub length: usize,
    /// One table per group, one entry per block: the page, or `None` where the group has let go of the block.
    pub tables: Vec<Vec<Option<usize>>>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdapterView {
    pub id: u32,
    /// Running requests that use it.
    pub users: usize,
    /// The pool pages that hold the adapter, in the order they were taken.
    pub pages: Vec<usize>,
}

/// The cache: the page that holds the block with this hash in this group.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CacheEntry {
    pub group: usize,
    pub hash: u64,
    pub page: usize,
}

/// Everything the site and the crate's checks look at, after each operation (the invariants of the lab run on it).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Snapshot {
    /// Every page, by id.
    pub pages: Vec<PageState>,
    /// The pages an allocation may take, in eviction order, the next to be taken first. The free pages and the cached pages, no others.
    pub queue: Vec<usize>,
    pub requests: Vec<RequestView>,
    pub adapters: Vec<AdapterView>,
    pub cache: Vec<CacheEntry>,
}

impl Snapshot {
    /// The lists in the order the wire writes them: requests and adapters by id, the cache by group and hash.
    pub fn normalized(mut self) -> Snapshot {
        self.requests.sort_by_key(|r| r.id);
        self.adapters.sort_by_key(|a| a.id);
        self.cache.sort_by_key(|e| (e.group, e.hash));
        self
    }
}

/// What a manager publishes (`kv-events@1`, in the shape of vLLM's KV events).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Event {
    /// A run of consecutive blocks entered the cache of `group`: their hashes, the hash of the block before the first (`None` when the
    /// run starts at the first block), the tokens of the whole run, and the request's adapter.
    Stored { group: usize, hashes: Vec<u64>, parent: Option<u64>, tokens: Vec<u32>, adapter: Option<u32> },
    /// A block left the cache of `group`, because its page was allocated to something else.
    Removed { group: usize, hash: u64 },
    /// The cache was reset.
    Cleared,
}


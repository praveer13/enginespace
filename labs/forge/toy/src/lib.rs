/// The most pans a rotation may be asked to hold over the wire.
pub const MAX_CAPACITY: usize = 4096;

const FILL: &str = "fill";
const HITS: &str = "hits";
const DUMP: &str = "dump";
const RECENCY: &str = "recency";
const CHURN: &str = "churn";

const FILL_LABEL: &str = "fill an empty rotation";
const HITS_LABEL: &str = "a held key is a hit and goes to the back";
const DUMP_LABEL: &str = "a full rotation dumps its front";
const RECENCY_LABEL: &str = "a hit saves a key from the next dump";
const CHURN_LABEL: &str = "seeded touches: every reply, and the whole order";

/// The checks, in grading order. Ids, labels and stages are the site's (src/forge/labs.ts), and `verify:labs` fails when they differ.
pub static CHECKS: [CheckDef; 5] = [
    CheckDef { id: FILL, label: FILL_LABEL, stage: 1, seeded: false, default_seed: 0, run: check_fill },
    CheckDef { id: HITS, label: HITS_LABEL, stage: 1, seeded: false, default_seed: 0, run: check_hits },
    CheckDef { id: DUMP, label: DUMP_LABEL, stage: 2, seeded: false, default_seed: 0, run: check_dump },
    CheckDef { id: RECENCY, label: RECENCY_LABEL, stage: 3, seeded: false, default_seed: 0, run: check_recency },
    CheckDef { id: CHURN, label: CHURN_LABEL, stage: 4, seeded: true, default_seed: 0x70C1, run: check_churn },
];

pub static LAB: Lab = Lab { id: LAB_ID, version: 1, checks: &CHECKS };

/* ------------------------------ the model ------------------------------ */

/// What a rotation must do, written for clarity. The harness judges your code against it, and it is not part of the module.
struct Model {
    capacity: usize,
    /// The front is the next to dump.
    keys: Vec<u32>,
}

impl Model {
    fn new(capacity: usize) -> Model {
        Model { capacity, keys: Vec::new() }
    }

    fn touch(&mut self, key: u32) -> Touch {
        if let Some(at) = self.keys.iter().position(|&k| k == key) {
            self.keys.remove(at);
            self.keys.push(key);
            return Touch::Hit;
        }
        let dumped = if self.keys.len() == self.capacity { Some(self.keys.remove(0)) } else { None };
        self.keys.push(key);
        Touch::Miss { dumped }
    }
}

/* ------------------------------ the words ------------------------------ */

/// A touch as the wire writes it.
pub fn show(touch: &Touch) -> String {
    match touch {
        Touch::Hit => "hit".into(),
        Touch::Miss { dumped: None } => "miss".into(),
        Touch::Miss { dumped: Some(key) } => format!("miss dump {key}"),
    }
}

/// An order as the wire writes it: next to dump first, or `-` when nothing is held.
pub fn list(keys: &[u32]) -> String {
    if keys.is_empty() {
        return "-".into();
    }
    keys.iter().map(u32::to_string).collect::<Vec<_>>().join(",")
}

/* ------------------------------ checks ------------------------------ */

fn touch_is(rotation: &mut Rotation, key: u32, want: Touch) -> Result<(), String> {
    let got = rotation.touch(key);
    if got == want {
        return Ok(());
    }
    Err(format!("touch {key} should answer `{}`, and yours answered `{}`", show(&want), show(&got)))
}

fn order_is(rotation: &Rotation, want: &[u32]) -> Result<(), String> {
    let got = rotation.order();
    if got == want {
        return Ok(());
    }
    Err(format!("the order should be {}, and yours is {} (next to dump first)", list(want), list(&got)))
}

fn len_is(rotation: &Rotation, want: usize) -> Result<(), String> {
    let got = rotation.len();
    if got == want {
        return Ok(());
    }
    Err(format!("the rotation should hold {want} keys, and yours says {got}"))
}

fn verdict(id: &'static str, label: &'static str, run: Result<&'static str, String>) -> Check {
    match run {
        Ok(message) => Check::pass(id, label, message),
        Err(message) => Check::fail(id, label, message),
    }
}

/// A touch that finds room: a miss that dumps nothing.
const ROOM: Touch = Touch::Miss { dumped: None };

fn fill() -> Result<&'static str, String> {
    let mut rotation = Rotation::new(4);
    for key in 1..=4 {
        touch_is(&mut rotation, key, ROOM)?;
    }
    len_is(&rotation, 4)?;
    order_is(&rotation, &[1, 2, 3, 4])?;
    Ok("four keys fit, in the order they came")
}

fn hits() -> Result<&'static str, String> {
    let mut rotation = Rotation::new(3);
    for key in 1..=3 {
        touch_is(&mut rotation, key, ROOM)?;
    }
    touch_is(&mut rotation, 1, Touch::Hit)?;
    order_is(&rotation, &[2, 3, 1])?;
    len_is(&rotation, 3)?;
    Ok("a held key is a hit, and it goes to the back")
}

fn dump() -> Result<&'static str, String> {
    let mut rotation = Rotation::new(3);
    for key in 1..=3 {
        touch_is(&mut rotation, key, ROOM)?;
    }
    touch_is(&mut rotation, 4, Touch::Miss { dumped: Some(1) })?;
    order_is(&rotation, &[2, 3, 4])?;
    len_is(&rotation, 3)?;
    touch_is(&mut rotation, 1, Touch::Miss { dumped: Some(2) })?;
    order_is(&rotation, &[3, 4, 1])?;
    Ok("the front is dumped, and the rotation stays full")
}

fn recency() -> Result<&'static str, String> {
    let mut rotation = Rotation::new(3);
    for key in 1..=3 {
        touch_is(&mut rotation, key, ROOM)?;
    }
    touch_is(&mut rotation, 1, Touch::Hit)?;
    touch_is(&mut rotation, 4, Touch::Miss { dumped: Some(2) })?;
    order_is(&rotation, &[3, 1, 4])?;
    Ok("the key touched most recently outlives the one that came later")
}

/// The seeded run: `ctx.seed` draws the capacity and the touches. The harness checks every reply against the model, and the whole order
/// and the count every 25 touches.
fn churn(seed: u32) -> Result<String, String> {
    const TOUCHES: usize = 2000;
    let mut rng = Rng::seeded(seed);
    let capacity = rng.range(3, 8);
    let keyspace = capacity * 2;
    let mut model = Model::new(capacity);
    let mut rotation = Rotation::new(capacity);
    for at in 0..TOUCHES {
        let key = 1 + rng.below(keyspace) as u32;
        let want = model.touch(key);
        let got = rotation.touch(key);
        if got != want {
            return Err(format!("touch {at} (key {key}) should answer `{}`, and yours answered `{}`", show(&want), show(&got)));
        }
        if at % 25 == 24 {
            if rotation.len() != model.keys.len() {
                return Err(format!("after touch {at}: the rotation should hold {} keys, and yours says {}", model.keys.len(), rotation.len()));
            }
            let order = rotation.order();
            if order != model.keys {
                return Err(format!("after touch {at}: the order should be {}, and yours is {}", list(&model.keys), list(&order)));
            }
        }
    }
    Ok(format!("{TOUCHES} touches on {capacity} pans, every reply and every order as the model has them"))
}

pub fn check_fill(_: &Ctx) -> Check {
    verdict(FILL, FILL_LABEL, fill())
}

pub fn check_hits(_: &Ctx) -> Check {
    verdict(HITS, HITS_LABEL, hits())
}

pub fn check_dump(_: &Ctx) -> Check {
    verdict(DUMP, DUMP_LABEL, dump())
}

pub fn check_recency(_: &Ctx) -> Check {
    verdict(RECENCY, RECENCY_LABEL, recency())
}

pub fn check_churn(ctx: &Ctx) -> Check {
    match churn(ctx.seed) {
        Ok(message) => Check::pass(CHURN, CHURN_LABEL, message),
        Err(message) => Check::fail(CHURN, CHURN_LABEL, message),
    }
}

/// The full suite on default seeds, in grading order (the v1 report's order).
pub fn self_checks() -> Vec<Check> {
    CHECKS.iter().map(|c| (c.run)(&Ctx { seed: c.default_seed, fresh: false })).collect()
}


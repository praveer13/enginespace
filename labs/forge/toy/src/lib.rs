/* ------------------------------ the bridge ------------------------------ */

thread_local! {
    static ROTATION: RefCell<Option<Rotation>> = const { RefCell::new(None) };
}

/// The site drives your module through this: it writes one command into module memory with `ks_alloc`, calls `ks_invoke`, and reads
/// the reply. The commands call YOUR rotation, the same code the checks call, and the bridge has no rotation logic of its own.
#[no_mangle]
pub extern "C" fn ks_invoke(in_ptr: u32, in_len: u32) -> u64 {
    kslab::install_panic_hook();
    let bytes = unsafe { kslab::input(in_ptr, in_len) };
    let command = String::from_utf8_lossy(bytes).into_owned();
    let reply = ROTATION.with(|rotation| bridge(&mut rotation.borrow_mut(), command.trim()));
    kslab::emit_str(&reply)
}

/// One command of the wire, on a rotation that may not exist yet. `cargo test` calls it too.
pub fn bridge(rotation: &mut Option<Rotation>, command: &str) -> String {
    const NOT_READY: &str = "err not initialized";
    let words: Vec<&str> = command.split_whitespace().collect();
    match words.as_slice() {
        ["init", capacity] => match capacity.parse::<usize>() {
            Ok(capacity) if (1..=MAX_CAPACITY).contains(&capacity) => {
                *rotation = Some(Rotation::new(capacity));
                "ok".into()
            }
            _ => format!("err bad capacity '{}'", kslab::clip(capacity, 20)),
        },
        ["touch", key] => match (rotation.as_mut(), key.parse::<u32>()) {
            (_, Err(_)) => format!("err bad key '{}'", kslab::clip(key, 20)),
            (None, Ok(_)) => NOT_READY.into(),
            (Some(rotation), Ok(key)) => show(&rotation.touch(key)),
        },
        ["len"] => rotation.as_ref().map_or(NOT_READY.into(), |rotation| rotation.len().to_string()),
        ["order"] => rotation.as_ref().map_or(NOT_READY.into(), |rotation| list(&rotation.order())),
        [] => "err empty command".into(),
        _ => format!("err unknown command '{}'", kslab::clip(command, 40)),
    }
}

/// What the bridge keeps between commands: the weights `pick` takes, the chain `round` verifies, and the coins `round` draws.
pub struct Bridge {
    weights: Vec<u32>,
    p: Vec<Vec<u32>>,
    q: Vec<Vec<u32>>,
    coins: Rng,
}

impl Default for Bridge {
    fn default() -> Bridge {
        Bridge { weights: Vec::new(), p: Vec::new(), q: Vec::new(), coins: Rng::seeded(0) }
    }
}

thread_local! {
    static BRIDGE: RefCell<Bridge> = RefCell::new(Bridge::default());
}

/// The site drives your module through this: it writes one command into module memory with `ks_alloc`, calls `ks_invoke`, and reads
/// the reply. The commands call YOUR functions, the same code the checks call, and the bridge has no sampling logic of its own.
#[no_mangle]
pub extern "C" fn ks_invoke(in_ptr: u32, in_len: u32) -> u64 {
    kslab::install_panic_hook();
    let bytes = unsafe { kslab::input(in_ptr, in_len) };
    let command = String::from_utf8_lossy(bytes).into_owned();
    let reply = BRIDGE.with(|bridge| self::bridge(&mut bridge.borrow_mut(), command.trim()));
    kslab::emit_str(&reply)
}

/// A comma-separated list of 1 to MAX_TOKENS whole numbers from 0 to TOTAL, or None. A weight is at most the total, so no sum of a list can
/// overflow a u32, whatever the learner's own arithmetic does with it.
fn numbers(text: &str) -> Option<Vec<u32>> {
    let items: Option<Vec<u32>> = text.split(',').map(|item| item.parse::<u32>().ok().filter(|&n| n <= TOTAL)).collect();
    items.filter(|items| items.len() <= MAX_TOKENS)
}

/// Distributions joined by `|`, each a list of weights that adds up to TOTAL, all over the same tokens.
fn distributions(text: &str) -> Result<Vec<Vec<u32>>, String> {
    let mut out: Vec<Vec<u32>> = Vec::new();
    for part in text.split('|') {
        let weights = numbers(part).ok_or_else(|| format!("err bad weights '{}'", kslab::clip(part, 40)))?;
        let sum: u32 = weights.iter().sum();
        if sum != TOTAL {
            return Err(format!("err a distribution adds up to {sum}, and it must add up to {TOTAL}"));
        }
        if out.first().is_some_and(|first| first.len() != weights.len()) {
            return Err("err the distributions have different numbers of tokens".into());
        }
        out.push(weights);
    }
    Ok(out)
}

/// One command of the wire, on a bridge that may not hold a chain yet. `cargo test` calls it too.
pub fn bridge(state: &mut Bridge, command: &str) -> String {
    let words: Vec<&str> = command.split_whitespace().collect();
    match words.as_slice() {
        ["accept", px, qx, u] => match (px.parse::<u32>(), qx.parse::<u32>(), u.parse::<u32>()) {
            (Ok(px), Ok(qx), Ok(u)) if px <= TOTAL && qx <= TOTAL && u < qx => String::from(if accept(px, qx, u) { "yes" } else { "no" }),
            (Ok(px), Ok(qx), Ok(_)) if px > TOTAL || qx > TOTAL => format!("err a weight is at most {TOTAL}"),
            (Ok(_), Ok(qx), Ok(u)) => format!("err the coin {u} is not below q ({qx})"),
            _ => format!("err bad numbers '{}'", kslab::clip(command, 40)),
        },
        ["residual", p, q] => match (numbers(p), numbers(q)) {
            (Some(p), Some(q)) if p.len() == q.len() => list(&residual(&p, &q)),
            (Some(_), Some(_)) => "err the two lists have different numbers of tokens".into(),
            _ => format!("err bad weights '{}'", kslab::clip(command, 40)),
        },
        ["weights", w] => match numbers(w) {
            Some(weights) => {
                state.weights = weights;
                "ok".into()
            }
            None => format!("err bad weights '{}'", kslab::clip(w, 40)),
        },
        ["pick", draw] => match draw.parse::<u32>() {
            Err(_) => format!("err bad draw '{}'", kslab::clip(draw, 20)),
            Ok(_) if state.weights.is_empty() => "err no weights are kept".into(),
            Ok(draw) if draw < state.weights.iter().sum::<u32>() => pick(&state.weights, draw).to_string(),
            Ok(draw) => format!("err the draw {draw} is not below the weights' sum"),
        },
        ["chain", p, q] => match (distributions(p), distributions(q)) {
            (Ok(p), Ok(q)) if p.len() == q.len() + 1 && p[0].len() == q[0].len() && q.len() <= MAX_DRAFTS => {
                state.p = p;
                state.q = q;
                "ok".into()
            }
            (Ok(_), Ok(_)) => format!("err a chain has 1 to {MAX_DRAFTS} q and one more p over the same tokens"),
            (Err(e), _) | (_, Err(e)) => e,
        },
        ["seed", n] => match n.parse::<u32>() {
            Ok(n) => {
                state.coins = Rng::seeded(n);
                "ok".into()
            }
            Err(_) => format!("err bad seed '{}'", kslab::clip(n, 20)),
        },
        ["round", draft] => {
            let tokens = draft.split(',').map(|x| x.parse::<usize>().ok()).collect::<Option<Vec<usize>>>();
            match tokens {
                _ if state.q.is_empty() => "err no chain is kept".into(),
                None => format!("err bad draft '{}'", kslab::clip(draft, 40)),
                Some(tokens) if tokens.len() != state.q.len() => format!("err the chain has {} drafts, and the round got {}", state.q.len(), tokens.len()),
                Some(tokens) => match tokens.iter().enumerate().find(|&(i, &x)| state.q[i].get(x).is_none_or(|&w| w == 0)) {
                    Some((i, x)) => format!("err the draft token {x} at position {i} has no weight in q"),
                    None => list(&verify(&state.p, &state.q, &tokens, &mut state.coins)),
                },
            }
        }
        [] => "err empty command".into(),
        _ => format!("err unknown command '{}'", kslab::clip(command, 40)),
    }
}

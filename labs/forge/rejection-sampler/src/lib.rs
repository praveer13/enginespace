/// The coins in 0..qx that `accept` keeps must number exactly min(px, qx).
fn kept_is(px: u32, qx: u32) -> Result<(), String> {
    let kept = (0..qx).filter(|&u| accept(px, qx, u)).count() as u32;
    let want = px.min(qx);
    if kept == want {
        return Ok(());
    }
    Err(format!("accept({px}, {qx}, u) keeps {kept} of the {qx} coins u in 0..{qx}, and a plate with p = {px} and q = {qx} is kept by exactly min(p, q) = {want} of them"))
}

fn accept_check(seed: u32) -> Result<String, String> {
    for (px, qx) in [(3, 5), (0, 5), (5, 5), (9, 5), (1, 1), (0, 1)] {
        kept_is(px, qx)?;
    }
    let mut rng = Rng::seeded(seed);
    let (p, q) = pair(&mut rng);
    let mut coins = 0;
    for (&px, &qx) in p.iter().zip(&q) {
        kept_is(px, qx)?;
        coins += qx;
    }
    Ok(format!("every coin of 6 hand cases and of the {coins} coins of a seeded pair: exactly min(p, q) of the coins keep a plate"))
}

fn check_accept(ctx: &Ctx) -> Check {
    verdict(ACCEPT, ACCEPT_LABEL, accept_check(ctx.seed))
}

fn residual_is(p: &[u32], q: &[u32]) -> Result<(), String> {
    let want: Vec<u32> = p.iter().zip(q).map(|(&a, &b)| a.saturating_sub(b)).collect();
    let got = residual(p, q);
    if got == want {
        return Ok(());
    }
    Err(format!("residual({}, {}) should be {}, the excess max(0, p - q) of every dish, and yours is {}", list(p), list(q), list(&want), list(&got)))
}

fn residual_check(seed: u32) -> Result<String, String> {
    for (p, q) in [(vec![5, 3, 0, 8], vec![2, 6, 0, 8]), (vec![0, 10], vec![10, 0]), (vec![4, 4], vec![4, 4])] {
        residual_is(&p, &q)?;
    }
    let mut rng = Rng::seeded(seed);
    for _ in 0..3 {
        let (p, q) = pair(&mut rng);
        residual_is(&p, &q)?;
    }
    Ok("the excess max(0, p - q) of 3 hand cases and 3 seeded pairs, dish by dish".into())
}

fn check_residual(ctx: &Ctx) -> Check {
    verdict(RESIDUAL, RESIDUAL_LABEL, residual_check(ctx.seed))
}

/// Every draw in 0..sum must pick a token, and token i must be picked by exactly weights[i] of them.
fn picked_as_often_as_weighed(weights: &[u32]) -> Result<(), String> {
    let sum: u32 = weights.iter().sum();
    let mut seen = vec![0u32; weights.len()];
    for draw in 0..sum {
        let token = pick(weights, draw);
        if token >= weights.len() {
            return Err(format!("pick({}, {draw}) answered token {token}, and there are only {} tokens", list(weights), weights.len()));
        }
        if weights[token] == 0 {
            return Err(format!("pick({}, {draw}) answered token {token}, which has weight 0 and can never be picked", list(weights)));
        }
        seen[token] += 1;
    }
    for (token, (&got, &want)) in seen.iter().zip(weights).enumerate() {
        if got != want {
            return Err(format!("over the draws 0..{sum}, pick({}, draw) picks token {token} {got} times, and its weight is {want}", list(weights)));
        }
    }
    Ok(())
}

fn pick_check(seed: u32) -> Result<String, String> {
    for weights in [vec![3, 0, 2], vec![0, 4], vec![1, 1, 1, 1], vec![5], vec![0, 0, 3, 0]] {
        picked_as_often_as_weighed(&weights)?;
    }
    let mut rng = Rng::seeded(seed);
    let (p, q) = pair(&mut rng);
    let excess: Vec<u32> = p.iter().zip(&q).map(|(&a, &b)| a.saturating_sub(b)).collect();
    picked_as_often_as_weighed(&excess)?;
    let small: Vec<u32> = split(&mut rng, 8, 120).into_iter().map(|w| w as u32).collect();
    picked_as_often_as_weighed(&small)?;
    Ok(format!("every draw of 5 hand lists, of a residual with {} draws and of a list of 8 weights: each dish is picked as often as its weight", excess.iter().sum::<u32>()))
}

fn check_pick(ctx: &Ctx) -> Check {
    verdict(PICK, PICK_LABEL, pick_check(ctx.seed))
}

const ROUNDS_PER_CASE: usize = 8;

/// One case of the `round` check: three drafts, of which at most one is sent back, and the words for what an exact verify step does.
struct Case {
    /// The position whose plate p rules out, so that it is sent back for sure and the residual has one dish. None: every plate is kept.
    sent_back: Option<usize>,
    /// The first target is flat, so that a rule which defers a send-back at a flat position has something to defer.
    flat: bool,
    why: &'static str,
}

const CASES: [Case; 4] = [
    Case { sent_back: Some(0), flat: false, why: "the first plate is sent back for sure, so the round stops there with the dish that replaces it" },
    Case { sent_back: Some(1), flat: false, why: "the first plate is kept for sure and the second is sent back for sure, so the round emits the first and then the dish that replaces the second" },
    Case { sent_back: None, flat: false, why: "every plate is kept for sure, so all of them go out and the bonus follows, picked from p after the last draft" },
    Case { sent_back: Some(0), flat: true, why: "the first plate is sent back for sure, whatever follows it: a round never keeps a dish that p rules out" },
];

/// The rounds whose outcome does not depend on a coin: a plate that p rules out is sent back for sure, a plate with p = q is kept for sure,
/// and a residual with one dish picks it whatever the draw. What any exact verify step emits for each of them is known.
fn round_check(seed: u32) -> Result<String, String> {
    let mut rng = Rng::seeded(seed);
    let mut coins = Rng::seeded(seed ^ 0x5eed);
    for case in &CASES {
        let (mut p, mut q, mut draft, mut replaced) = (Vec::new(), Vec::new(), Vec::new(), 0);
        for i in 0..3 {
            let mut d = six(&mut rng);
            if case.sent_back == Some(i) {
                let (mut x, mut t) = two_smallest(&d);
                while case.flat && !flat(&sure_reject(&d, x, t)) {
                    d = six(&mut rng);
                    (x, t) = two_smallest(&d);
                }
                p.push(sure_reject(&d, x, t));
                draft.push(x);
                replaced = t;
            } else {
                p.push(d.clone());
                draft.push(draft_from(std::slice::from_ref(&d), &mut rng)[0]);
            }
            q.push(d);
        }
        // The bonus position has one dish with all the weight, so the bonus is known too.
        let bonus = rng.below(6);
        let mut last = vec![0; 6];
        last[bonus] = TOTAL;
        p.push(last);
        let want: Vec<usize> = match case.sent_back {
            Some(i) => draft[..i].iter().copied().chain(std::iter::once(replaced)).collect(),
            None => draft.iter().copied().chain(std::iter::once(bonus)).collect(),
        };
        for _ in 0..ROUNDS_PER_CASE {
            let got = verify(&p, &q, &draft, &mut coins);
            if got != want {
                return Err(format!("verify with the draft {} should emit {}, and yours emitted {}: {}", list(&draft), list(&want), list(&got), case.why));
            }
        }
    }
    Ok(format!("{} cases of {ROUNDS_PER_CASE} rounds in which no coin matters: a stop at the first send-back, a stop at the second, a full run with the bonus, and a flat target", CASES.len()))
}

fn check_round(ctx: &Ctx) -> Check {
    verdict(ROUND, ROUND_LABEL, round_check(ctx.seed))
}

/// Draws per seed, and the limit of the statistic at 5 degrees of freedom at α = 1e-4: the site's CRITICAL['1e-4'][5] ÷ 1000
/// (packages/sim/spec/critical.ts), which tests/forge checks against this number [estimated].
const ROUNDS: usize = 20_000;
const LIMIT: f64 = 25.745;
const LIMIT_TEXT: &str = "25.745";

/// A statistic with one decimal, written without the float formatter, which is a good deal of code in a module this small.
fn tenths(x: f64) -> String {
    let t = (x * 10.0 + 0.5) as u64;
    format!("{}.{}", t / 10, t % 10)
}

/// Pearson's statistic of `counts` against `p`, a distribution of dishes that all have weight.
fn chi_square(counts: &[u32], p: &[u32]) -> f64 {
    let n = f64::from(counts.iter().sum::<u32>());
    counts
        .iter()
        .zip(p)
        .map(|(&seen, &weight)| {
            let want = n * f64::from(weight) / f64::from(TOTAL);
            let gap = f64::from(seen) - want;
            gap * gap / want
        })
        .sum()
}

fn exact_check(seed: u32) -> Result<String, String> {
    let mut rng = Rng::seeded(seed);
    // Two drafts, with a flat first target: a lossy rule that defers at a flat position has something to defer.
    let (p, q) = loop {
        let ((p0, q0), (p1, q1), p2) = (pair(&mut rng), pair(&mut rng), six(&mut rng));
        if flat(&p0) {
            break (vec![p0, p1, p2], vec![q0, q1]);
        }
    };
    let mut stats = Vec::new();
    for _ in 0..2 {
        let sub = rng.next() as u32;
        let (mut drafts, mut coins) = (Rng::seeded(sub), Rng::seeded(sub ^ 0xc01d));
        let mut counts = vec![0u32; 6];
        for _ in 0..ROUNDS {
            let draft = draft_from(&q, &mut drafts);
            let out = verify(&p, &q, &draft, &mut coins);
            match out.first() {
                Some(&token) if token < 6 => counts[token] += 1,
                Some(token) => return Err(format!("a round emitted the token {token}, and there are 6 tokens")),
                None => return Err("a round emitted no token: it emits at least one".into()),
            }
        }
        let stat = chi_square(&counts, &p[0]);
        if stat > LIMIT {
            // The dish whose count is furthest from its share, in whole counts: share = ROUNDS * weight / TOTAL.
            let share = |t: usize| (ROUNDS as u64 * u64::from(p[0][t]) / u64::from(TOTAL)) as i64;
            let worst = (0..6).max_by_key(|&t| (i64::from(counts[t]) - share(t)).abs()).unwrap_or(0);
            return Err(format!(
                "over {ROUNDS} rounds the first token should follow p: chi-square {} on 5 degrees of freedom is over the limit {LIMIT_TEXT}, and the dish furthest from its share is token {worst} (expected {}, seen {})",
                tenths(stat),
                share(worst),
                counts[worst]
            ));
        }
        stats.push(stat);
    }
    Ok(format!("chi-square {} and {} on 5 degrees of freedom over {ROUNDS} rounds each, under the limit {LIMIT_TEXT} (α = 1e-4)", tenths(stats[0]), tenths(stats[1])))
}

fn check_exact(ctx: &Ctx) -> Check {
    verdict(EXACT, EXACT_LABEL, exact_check(ctx.seed))
}


/*
 * W1-T10: the forge labs, held to each other without a Rust toolchain (verify:labs holds the builds themselves). The lab's checks are
 * written twice, in Rust (the crate's own checks, which `cargo test` runs) and in TypeScript (the site's, which credit comes from), and the
 * two lists must agree. The crate, the toolchain pin, the kit and the committed builds are read from the files, so a change to one that
 * leaves the others behind fails here. W1-T22 made the tests of a crate run for every lab of the registry: a lab adds a row to `CRATES`.
 */
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'bun:test'
import { load } from 'js-yaml'
import { FORGE_LAB_IDS, isForgeLab } from '../../src/forge/ids'
import { FORGE_LABS } from '../../src/forge/labs'
import { readBestiary } from '../../scripts/labs/bestiary'
import { parsePin } from '../../scripts/labs/toolchain'
import { between, read, root, tableRows } from '../ci/support'

const forge = path.join(root, 'labs/forge')
/** The labs whose crates this file checks, with the file that a learner edits and the reference that replaces it. (The rejection-sampler's are checked in tests/forge/rejection-sampler.test.ts.) */
const CRATES = [
  { lab: 'toy', todo: 'rotation.rs', reference: 'reference/rotation.rs' },
  { lab: 'hybrid-kv', todo: 'manager.rs', reference: 'reference/manager.rs' },
] as const
const sha256 = (file: string) => createHash('sha256').update(readFileSync(file)).digest('hex')

describe('the registry', () => {
  test('ids.ts lists the labs that labs.ts grades, and nothing else', () => {
    expect([...FORGE_LAB_IDS].sort()).toEqual(Object.keys(FORGE_LABS).sort())
    for (const [id, lab] of Object.entries(FORGE_LABS)) expect(lab.id).toBe(id)
    for (const id of Object.keys(FORGE_LABS)) expect(isForgeLab(id)).toBe(true)
    expect(isForgeLab('no-such-lab')).toBe(false)
    expect(isForgeLab(undefined)).toBe(false)
  })

  test('every lab names a crate that is in the workspace, and the file it builds', () => {
    const workspace = read('labs/forge/Cargo.toml')
    const members = [...(/members\s*=\s*\[([^\]]*)\]/.exec(workspace)?.[1] ?? '').matchAll(/"([^"]+)"/g)].map((m) => m[1])
    // The kit and one crate for each lab: a lab that is added to the registry is added to the workspace too.
    expect([...members].sort()).toEqual(['kit', ...Object.values(FORGE_LABS).map((lab) => lab.crate)].sort())
    for (const lab of Object.values(FORGE_LABS)) {
      expect(members).toContain(lab.crate)
      expect(lab.wasm).toBe(`${lab.crate.replaceAll('-', '_')}.wasm`)
    }
  })
})

for (const { lab, todo, reference } of CRATES) {
  const crate = path.join(forge, FORGE_LABS[lab].crate)
  const checks = FORGE_LABS[lab].checks

  describe(`the ${lab} lab's checks, in Rust and in TypeScript`, () => {
    const source = read(`labs/forge/${FORGE_LABS[lab].crate}/src/lib.rs`)
    const constants = new Map([...source.matchAll(/^const (\w+): &str = "([^"]*)";$/gm)].map((m) => [m[1], m[2]]))
    const rows = [...source.matchAll(/CheckDef \{ id: (\w+), label: (\w+), stage: (\d+), seeded: (true|false), default_seed: (\w+), run: \w+ \}/g)]

    test('the crate declares the checks that the site grades: ids, labels, stages, which are seeded, and the default seed', () => {
      expect(rows).toHaveLength(checks.length)
      const declared = rows.map((m) => ({
        id: constants.get(m[1]),
        label: constants.get(m[2]),
        stage: Number(m[3]),
        seeded: m[4] === 'true',
        defaultSeed: Number(m[5]),
      }))
      expect(declared).toEqual(checks.map(({ id, label, stage, seeded, defaultSeed }) => ({ id, label, stage, seeded, defaultSeed })))
    })

    test('the harness is marked DO NOT EDIT, and the learner\'s file is the only one marked TODO(you)', () => {
      expect(source).toContain('DO NOT EDIT this file')
      const marked = readdirSync(path.join(crate, 'src'), { recursive: true })
        .map(String)
        .filter((file) => file.endsWith('.rs') && /^\/\/! TODO\(you\)/m.test(readFileSync(path.join(crate, 'src', file), 'utf8')))
      expect(marked).toEqual([todo])
    })

    test(`the module is named ${lab}, and ${lab}@reference only when the reference feature is on`, () => {
      expect(source).toMatch(new RegExp(`#\\[cfg\\(not\\(feature = "reference"\\)\\)\\]\\s*const LAB_ID: &str = "${lab}";`))
      expect(source).toMatch(new RegExp(`#\\[cfg\\(feature = "reference"\\)\\]\\s*const LAB_ID: &str = "${lab}@reference";`))
    })

    if (lab === 'toy') {
      test('the wire in the crate\'s header is the wire in the oracle\'s', () => {
        const wire = (text: string) => [...text.matchAll(/^(?:\/\/[!/]?\s+)(init <capacity>|touch <key>|len|order)\s+(.*?)\s*→\s*(.*)$/gm)].map((m) => [m[1], m[3].trim()])
        expect(wire(source)).toEqual(wire(read('packages/sim/forge/toy.ts')))
        expect(wire(source).map(([verb]) => verb)).toEqual(['init <capacity>', 'touch <key>', 'len', 'order'])
      })
    }
  })

  describe(`the ${lab} bestiary and builds`, () => {
    const bestiary = readBestiary(crate)
    const ids = checks.map((check) => check.id)
    const manifest = read(`labs/forge/${FORGE_LABS[lab].crate}/Cargo.toml`)

    test('every member names checks the lab has, a feature the crate has, and a source file', () => {
      expect(bestiary.lab).toBe(lab)
      for (const member of bestiary.members) {
        for (const id of [...Object.keys(member.fails), ...member.passes, ...(member.only ?? [])]) expect(ids, `${member.id} names ${id}`).toContain(id)
        expect(manifest).toMatch(new RegExp(`^${member.feature} = \\[\\]`, 'm'))
        expect(existsSync(path.join(crate, 'bestiary', `${member.id}.rs`)), `bestiary/${member.id}.rs`).toBe(true)
        expect(read(`labs/forge/${FORGE_LABS[lab].crate}/src/lib.rs`)).toContain(`feature = "${member.feature}"`)
        // What a member must fail, it does not also pass.
        for (const id of Object.keys(member.fails)) expect(member.passes).not.toContain(id)
      }
    })

    test('the reference solution is its own file, and the features are the ones the verify gate builds', () => {
      expect(existsSync(path.join(crate, reference))).toBe(true)
      for (const feature of ['reference', 'solved']) expect(manifest).toMatch(new RegExp(`^${feature} = \\[\\]`, 'm'))
    })

    test('the committed builds are one for each variant, and each begins like WebAssembly', () => {
      const names = ['template', 'reference', 'solved', ...bestiary.members.map((m) => m.id)].sort()
      const files = readdirSync(path.join(root, 'tests/fixtures/forge', lab)).sort()
      expect(files).toEqual(names.map((name) => `${name}.wasm`))
      for (const file of files) {
        const head = readFileSync(path.join(root, 'tests/fixtures/forge', lab, file)).subarray(0, 4)
        expect([...head]).toEqual([0x00, 0x61, 0x73, 0x6d])
      }
    })
  })
}

describe('the workspace', () => {
  test('the kit is the vendored kslab, byte for byte', () => {
    for (const file of ['Cargo.toml', 'src/lib.rs']) {
      expect(sha256(path.join(forge, 'kit', file)), file).toBe(sha256(path.join(root, 'vendor/kernelspace/labs/kit', file)))
    }
    // The vendored hashes are VENDOR.md's, so the copy is the pinned commit's.
    const vendor = read('vendor/kernelspace/VENDOR.md')
    expect(vendor).toContain(sha256(path.join(forge, 'kit/src/lib.rs')))
    expect(vendor).toContain(sha256(path.join(forge, 'kit/Cargo.toml')))
  })

  test('the toolchain pin is the one ARCHITECTURE §10.3 lists and labs.yml installs, with the wasm32 target', () => {
    const pin = parsePin(read('labs/forge/rust-toolchain.toml'))
    const row = tableRows(between(read('docs/ARCHITECTURE.md'), '### 10.3 Pinned tools and actions', 'Every job sets')).find((cells) => cells[0] === 'Rust')
    expect(row?.[1]).toBe(`${pin.channel}, with \`${pin.targets[0]}\``)
    const workflow = load(read('.github/workflows/labs.yml')) as { env?: { RUST_TOOLCHAIN?: string } }
    expect(workflow.env?.RUST_TOOLCHAIN).toBe(pin.channel)
    expect(pin.targets).toEqual(['wasm32-unknown-unknown'])
  })

  test('the lockfile holds the kit and the labs\' crates and no other, so that nothing is fetched', () => {
    const lock = read('labs/forge/Cargo.lock')
    expect([...lock.matchAll(/^name = "([^"]+)"$/gm)].map((m) => m[1]).sort()).toEqual(['kslab', ...Object.values(FORGE_LABS).map((lab) => lab.crate)].sort())
    expect(lock).not.toContain('source = ')
  })

  test('target/ is ignored, and the workspace holds a toolchain file, a lockfile and the kit', () => {
    expect(read('labs/forge/.gitignore')).toContain('target/')
    for (const file of ['Cargo.toml', 'Cargo.lock', 'rust-toolchain.toml', 'kit/Cargo.toml', 'kit/src/lib.rs']) expect(existsSync(path.join(forge, file)), file).toBe(true)
  })

  test('the forge job tests the crates against the reference: the template\'s own checks are red until a learner writes the file', () => {
    const workflow = load(read('.github/workflows/labs.yml')) as { jobs?: { forge?: { steps?: { run?: string }[] } } }
    const runs = (workflow.jobs?.forge?.steps ?? []).flatMap((step) => (step.run === undefined ? [] : [step.run]))
    expect(runs.find((run) => run.startsWith('cargo test'))).toContain('--features reference')
  })
})

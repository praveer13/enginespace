/*
 * W1-T27: the rejection-sampler lab, held to itself without a Rust toolchain (verify:labs holds the builds themselves). The lab's checks are
 * written twice, in Rust (the crate's own checks, which `cargo test` runs) and in TypeScript (the site's, which credit comes from), and the
 * two lists must agree, as must the wire, the numbers that both sides use, and the bestiary and the builds. The crate, the bestiary and
 * the committed builds are read from the files, so a change to one that leaves the others behind fails here.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, test } from 'bun:test'
import { FORGE_LAB_IDS, isForgeLab } from '../../src/forge/ids'
import { FORGE_LABS } from '../../src/forge/labs'
import { readBestiary } from '../../scripts/labs/bestiary'
import { CRITICAL, LAB_DRAWS, LAB_LEVEL, LAB_SEEDS } from '../../packages/sim/spec'
import { SAMPLER_LIMITS } from '../../packages/sim/forge'
import { buildArchive } from '../../scripts/pack-labs'
import { read, root } from '../ci/support'

const lab = FORGE_LABS['rejection-sampler']
const crate = path.join(root, 'labs/forge/rejection-sampler')
const source = read('labs/forge/rejection-sampler/src/lib.rs')

describe('the registry', () => {
  test('the lab is listed, graded, and built from the crate beside it', () => {
    expect(isForgeLab('rejection-sampler')).toBe(true)
    expect(FORGE_LAB_IDS).toContain('rejection-sampler')
    expect(lab).toMatchObject({ id: 'rejection-sampler', crate: 'rejection-sampler', wasm: 'rejection_sampler.wasm' })
    expect(lab.checks.map((check) => check.id)).toEqual(['accept', 'residual', 'pick', 'round', 'exact'])
  })

  test('the lab\'s words are the kitchen\'s and the engine\'s, in two sentences (GAMES.md §2.6)', () => {
    expect(lab.title).toBe('Keep or Re-plate')
    expect(lab.lead.split(/(?<=[.])\s+/)).toHaveLength(2)
    expect(lab.engineTerm).toContain('rejection sampler')
  })
})

describe('the checks, in Rust and in TypeScript', () => {
  const constants = new Map([...source.matchAll(/^const (\w+): &str = "([^"]*)";$/gm)].map((m) => [m[1], m[2]]))
  const rows = [...source.matchAll(/CheckDef \{ id: (\w+), label: (\w+), stage: (\d+), seeded: (true|false), default_seed: (\w+), run: \w+ \}/g)]

  test('the crate declares five checks, and the site grades the same five: ids, labels, stages, which are seeded, and the default seed', () => {
    expect(rows).toHaveLength(lab.checks.length)
    const declared = rows.map((m) => ({
      id: constants.get(m[1]),
      label: constants.get(m[2]),
      stage: Number(m[3]),
      seeded: m[4] === 'true',
      defaultSeed: Number(m[5]),
    }))
    expect(declared).toEqual(lab.checks.map(({ id, label, stage, seeded, defaultSeed }) => ({ id, label, stage, seeded, defaultSeed })))
  })

  test('every check has a stage from 1 to 4 in order, a default seed of its own, and says what it catches', () => {
    const stages = lab.checks.map((check) => check.stage)
    expect(stages).toEqual([...stages].sort((a, b) => a - b))
    expect(new Set(lab.checks.map((check) => check.defaultSeed)).size).toBe(lab.checks.length)
    for (const check of lab.checks) expect(check.catches.length).toBeGreaterThan(40)
  })

  test('the harness is marked DO NOT EDIT, and the learner\'s file is the only one marked TODO(you)', () => {
    expect(source).toContain('DO NOT EDIT this file')
    const marked = readdirSync(path.join(crate, 'src'), { recursive: true })
      .map(String)
      .filter((file) => file.endsWith('.rs') && /^\/\/! TODO\(you\)/m.test(readFileSync(path.join(crate, 'src', file), 'utf8')))
    expect(marked).toEqual(['verify.rs'])
  })

  test('the module is named rejection-sampler, and rejection-sampler@reference only when the reference feature is on', () => {
    expect(source).toMatch(/#\[cfg\(not\(feature = "reference"\)\)\]\s*const LAB_ID: &str = "rejection-sampler";/)
    expect(source).toMatch(/#\[cfg\(feature = "reference"\)\]\s*const LAB_ID: &str = "rejection-sampler@reference";/)
  })

  test('the numbers that both sides use are the same: the total, the limits of a chain, the draws, and the chi-square limit at 5 degrees of freedom', () => {
    const num = (name: string) => Number(new RegExp(`${name}: (?:u32|usize) = ([\\d_]+);`).exec(source)?.[1]?.replaceAll('_', ''))
    expect(num('TOTAL')).toBe(SAMPLER_LIMITS.total)
    expect(num('MAX_TOKENS')).toBe(SAMPLER_LIMITS.maxTokens)
    expect(num('MAX_DRAFTS')).toBe(SAMPLER_LIMITS.maxDrafts)
    expect(num('ROUNDS')).toBe(LAB_DRAWS)
    // The crate's own exactness check uses six dishes, so 5 degrees of freedom, at the level the site tests at.
    const limit = CRITICAL[LAB_LEVEL][5] / 1000
    expect(Number(/const LIMIT: f64 = ([\d.]+);/.exec(source)?.[1])).toBe(limit)
    expect(/const LIMIT_TEXT: &str = "([\d.]+)";/.exec(source)?.[1]).toBe(String(limit))
    expect(LAB_SEEDS).toBe(2)
    expect(LAB_LEVEL).toBe('1e-4')
    expect(source).toContain('for _ in 0..2 {')
  })

  test('the wire in the crate\'s header is the wire in the oracle\'s', () => {
    const wire = (text: string) => [...text.matchAll(/^(?:\/\/[!/]?\s+)(accept|residual|weights|pick|chain|seed|round)\b.*?→\s*(.*)$/gm)].map((m) => [m[1], m[2].trim()])
    expect(wire(source)).toEqual(wire(read('packages/sim/forge/rejection-sampler.ts')))
    expect(wire(source).map(([verb]) => verb)).toEqual(['accept', 'residual', 'weights', 'pick', 'chain', 'seed', 'round'])
  })

  test('the harness answers each verb of the wire, and the bridge has no sampling of its own', () => {
    for (const verb of ['accept', 'residual', 'weights', 'pick', 'chain', 'seed', 'round']) expect(source).toContain(`["${verb}"`)
    // The bridge calls the learner's functions and nothing else: no rng draw of its own between `pub fn bridge` and the end of the file.
    const bridge = source.slice(source.indexOf('pub fn bridge('))
    expect(bridge).not.toMatch(/\.below\(|\.next\(\)|walk\(/)
  })
})

describe('the bestiary and the builds', () => {
  const bestiary = readBestiary(crate)
  const ids = lab.checks.map((check) => check.id)
  const manifest = read('labs/forge/rejection-sampler/Cargo.toml')

  test('the six wrong verify steps of TR6 §5, each with a feature, a source file and checks of the lab', () => {
    expect(bestiary.lab).toBe('rejection-sampler')
    expect(bestiary.members.map((member) => member.id)).toEqual([
      'accept-if-p-over-q',
      'resample-from-p',
      'resample-from-q',
      'residual-off-by-one',
      'boundary-inclusive',
      'fly-lossy',
    ])
    for (const member of bestiary.members) {
      for (const id of [...Object.keys(member.fails), ...member.passes, ...(member.only ?? [])]) expect(ids, `${member.id} names ${id}`).toContain(id)
      expect(member.feature).toBe(`bestiary-${member.id}`)
      expect(manifest).toMatch(new RegExp(`^${member.feature} = \\[\\]`, 'm'))
      expect(existsSync(path.join(crate, 'bestiary', `${member.id}.rs`)), `bestiary/${member.id}.rs`).toBe(true)
      expect(source).toContain(`feature = "${member.feature}"`)
      expect(source).toContain(`#[path = "../bestiary/${member.id}.rs"]`)
      // What a member must fail, it does not also pass; and it runs the checks it names, when it limits them.
      for (const id of Object.keys(member.fails)) expect(member.passes).not.toContain(id)
      if (member.only !== undefined) for (const id of [...Object.keys(member.fails), ...member.passes]) expect(member.only).toContain(id)
    }
  })

  test('every check of the lab catches at least one member, and the headline check, the chi-square, is named for the members it is sure of', () => {
    const caught = new Set(bestiary.members.flatMap((member) => Object.keys(member.fails)))
    for (const id of ids) expect(caught.has(id), `${id} fails no member`).toBe(true)
    const byExact = bestiary.members.filter((member) => 'exact' in member.fails).map((member) => member.id)
    expect(byExact).toEqual(['resample-from-p', 'resample-from-q', 'residual-off-by-one', 'fly-lossy'])
  })

  test('the reference solution is its own file, and the features are the ones the verify gate builds', () => {
    expect(existsSync(path.join(crate, 'reference/verify.rs'))).toBe(true)
    for (const feature of ['reference', 'solved']) expect(manifest).toMatch(new RegExp(`^${feature} = \\[\\]`, 'm'))
  })

  test('each bestiary file cites the claims it stands on, and the claims are there', () => {
    const claims = ['content/claims/sglang/spec.yaml', 'content/claims/vllm/spec.yaml'].map(read).join('\n')
    const files = [...bestiary.members.map((member) => path.join(crate, 'bestiary', `${member.id}.rs`)), path.join(root, 'packages/sim/forge/rejection-sampler.ts'), path.join(crate, 'src/lib.rs')]
    const cited = new Set(files.flatMap((file) => [...readFileSync(file, 'utf8').matchAll(/\b((?:sglang|vllm)\.spec\.[a-z0-9.-]+[a-z0-9])/g)].map((m) => m[1])))
    expect([...cited].sort()).toContain('sglang.spec.pr-35798')
    for (const id of cited) expect(claims, `claim ${id}`).toContain(`- id: ${id}\n`)
  })

  test('the committed builds are one for each variant, and each begins like WebAssembly', () => {
    const names = ['template', 'reference', 'solved', ...bestiary.members.map((member) => member.id)].sort()
    const files = readdirSync(path.join(root, 'tests/fixtures/forge/rejection-sampler')).sort()
    expect(files).toEqual(names.map((name) => `${name}.wasm`))
    for (const file of files) {
      const head = readFileSync(path.join(root, 'tests/fixtures/forge/rejection-sampler', file)).subarray(0, 4)
      expect([...head]).toEqual([0x00, 0x61, 0x73, 0x6d])
    }
  })
})

describe('the zip that a learner downloads', () => {
  const archive = buildArchive(lab)
  const member = (file: string) => new TextDecoder().decode(archive.members.find((m) => m.path === file)?.data ?? new Uint8Array(0))

  test('has the learner\'s file and the harness that the guard protects, and withholds the solution and the wrong modules', () => {
    expect(archive.todoFile).toBe('rejection-sampler/src/verify.rs')
    expect(archive.harnessFile).toBe('rejection-sampler/src/lib.rs')
    expect(archive.members.map((m) => m.path).filter((file) => /reference|bestiary|\.wasm$/.test(file))).toEqual([])
    const template = member(archive.todoFile)
    expect(template).toContain('todo!(')
    expect(template).not.toContain('saturating_sub')
    expect(template).not.toMatch(/u < px\s*$/m)
  })

  test('tells the learner the five checks, with what each catches, and agents the check ids to use', () => {
    const readme = member('README.md')
    const agents = member('AGENTS.md')
    for (const check of lab.checks) {
      expect(readme).toContain(`\`${check.id}\``)
      expect(readme).toContain(check.catches)
      expect(agents).toContain(`\`${check.id}\`: ${check.label}`)
    }
    expect(readme).toContain('rejection_sampler.wasm')
    expect(readme).toContain('/labs/rejection-sampler')
  })

  test('denies edits to the two protected files in the settings of the agent kit', () => {
    const settings = JSON.parse(member('.claude/settings.json')) as { permissions?: { deny?: string[] } }
    const deny = (settings.permissions?.deny ?? []).join('\n')
    expect(deny).toContain('rejection-sampler/src/verify.rs')
    expect(deny).toContain('rejection-sampler/src/lib.rs')
  })
})
